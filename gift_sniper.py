# Тихий счётчик: сводка шлётся раз в HEARTBEAT_MIN минут, а не каждый цикл.
# Уведомление, приходящее каждую минуту, перестают читать через час — и
# пропускают то единственное, ради которого всё затевалось.
_last_heartbeat = 0.0


def notify_heartbeat(snapshots: list, force: bool = False):
    """
    Периодическая сводка «бот жив, вот что на рынке» в Telegram.

    Зачем отдельно от notify(): следить за ботом с телефона имеет смысл
    только если сообщения приходят редко и по делу. Молчащий бот неотличим
    от упавшего, а болтливый — от шума.
    """
    global _last_heartbeat
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        return False
    now = time.time()
    if not force and (now - _last_heartbeat) < HEARTBEAT_MIN * 60:
        return False
    _last_heartbeat = now

    lines = [f"📊 Снайпер жив ({datetime.now(timezone.utc):%H:%M UTC})"]
    for snap in snapshots:
        if snap.get("sample_size", 0) == 0:
            lines.append(f"• {_short(snap.get('collection', '?'))}: данных нет")
            continue
        mark = "" if snap.get("floor_reliable") else " ⚠️ выборка мала"
        lines.append(f"• {_short(snap.get('collection', '?'))}: "
                     f"floor {snap['floor']:.2f} | лотов {snap['sample_size']}"
                     f"{mark}")
    if BANKROLL_TON > 0:
        lines.append(f"Банк: {available_bankroll()} TON свободно, "
                     f"позиций {open_positions_count()}")

    global _finds_suppressed
    if _finds_suppressed:
        lines.append(f"Находок не отправлено из-за лимита: {_finds_suppressed}")
        _finds_suppressed = 0

    notify("\n".join(lines))
    return True


# Метки времени отправленных находок за последний час и счётчик подавленных.
# Подавленные обязаны быть видимы: «тихо не отправили» и «находок не было» —
# это разные вещи, и перепутать их значит решить, что рынок мёртв.
_find_sent_ts: list = []
_finds_suppressed = 0


def notify_find(item: dict, snap: dict, ev: dict) -> bool:
    """
    Сообщает о ЛОТЕ, прошедшем детерминированный фильтр. True, если отправлено.

    Зачем отдельно от уведомления о покупке: пока бот в DRY_RUN (а он в нём
    будет долго — живой режим закрыт воротами), покупок не существует, и без
    этого сообщения владелец не видит РАБОТЫ бота вообще. Смотреть в лог на
    VPS с телефона никто не станет.

    Шлётся ДО обращения к Claude и независимо от него: фильтр уже сказал «да»,
    и это факт о рынке, а не мнение. Находка при этом ещё не покупка — её
    может отклонить ИИ или срезать риск-лимит, и в сообщении это честно
    названо ожиданием, а не результатом.
    """
    global _finds_suppressed
    if FIND_NOTIFY_MAX_PER_HOUR <= 0:
        return False
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        return False

    now = time.time()
    _find_sent_ts[:] = [t for t in _find_sent_ts if now - t < 3600]
    if len(_find_sent_ts) >= FIND_NOTIFY_MAX_PER_HOUR:
        _finds_suppressed += 1
        log.info(f"{_Color.GREY}Находка не отправлена: за час уже "
                 f"{FIND_NOTIFY_MAX_PER_HOUR} уведомлений.{_Color.RESET}")
        return False
    _find_sent_ts.append(now)

    addr = item.get("address", "")
    # Две цены и разбор, а не одно число «профит». Владельцу, который получил
    # находку в телефон, надо знать, за сколько покупать и за сколько потом
    # выставлять — иначе уведомление сообщает о возможности, которой нельзя
    # воспользоваться руками.
    lines = [f"🎯 Находка: скидка {ev['discount_pct']}% от floor",
             f"floor коллекции {snap['floor']} TON"]
    lines += explain_trade(ev, snap, item)

    if ev.get("rarity_pct") is not None:
        lines.append(f"редкость {ev['rarity_pct']}% по «{ev['rarest_trait']}»")

    # Почему находка может не стать покупкой — говорим сразу, иначе владелец
    # ждёт сделки, которой не будет, и считает бота сломанным.
    if DRY_RUN:
        lines.append("режим симуляции — покупки НЕ будет")
    elif not SELLING_IMPLEMENTED:
        lines.append("продажи нет как кода — живой режим закрыт")
    else:
        cap = max_position_size(ev["roi_pct"])
        if ev["buy_price"] > cap:
            lines.append(f"⚠️ не влезет в лимит: потолок сделки {cap} TON")

    # Три способа добраться до лота вместо одного. Форма ссылки на площадку
    # сверена с getgems.io (getgems.io/nft/<user-friendly адрес>), но пустая
    # страница всё равно возможна — если лот УЖЕ УШЁЛ С ПРОДАЖИ. Это не баг,
    # а рынок, и обозреватель отличает одно от другого: он резолвит любой
    # адрес всегда и показывает текущего владельца.
    #
    # Витрины понимают user-friendly форму, а TonAPI отдаёт raw. Подставить
    # raw в ссылку значит отправить владельца на пустую страницу.
    link_addr = friendly_ton_address(addr)
    if GIFT_URL_TEMPLATE:
        lines.append(GIFT_URL_TEMPLATE.format(address=link_addr))
    if EXPLORER_URL_TEMPLATE:
        lines.append(EXPLORER_URL_TEMPLATE.format(address=link_addr))
    lines.append(link_addr)

    # Кнопки нужны потому, что режим сейчас РУЧНОЙ: бот находит, а покупает и
    # выставляет владелец. Без отметки «купил» позиция не попадает в БД, и ни
    # PnL, ни риск-лимиты про неё не знают — учёт становится фикцией.
    action_id = tg_action_create(item, ev)
    body = _tg_call("sendMessage", {
        "chat_id": TELEGRAM_CHAT_ID,
        "text": "\n".join(lines),
        "reply_markup": _find_buttons(action_id),
    })
    if body is None:
        return False
    tg_action_update(action_id,
                     message_id=(body.get("result") or {}).get("message_id"))
    return True


def poll_telegram_callbacks() -> int:
    """
    Забирает нажатия кнопок «Купил / Продал» и применяет их. Возвращает число
    обработанных.

    Почему это отдельный шаг, а не «кнопки просто работают». Telegram не
    доставляет нажатие сам: бот обязан ИЛИ держать вебхук, ИЛИ спрашивать
    `getUpdates`. Вебхук требует публичного адреса, которого у домашнего ПК
    нет, поэтому спрашиваем — раз в цикл, без ожидания (`timeout=0`), чтобы
    не растягивать наблюдение.

    Смещение (`tg_offset`) хранится В БД. Без этого бот, перезапущенный
    после нажатия, проглотил бы его заново и открыл вторую позицию на тот же
    лот — тот же принцип, по которому в БД лежат риск-лимиты и расход квоты.

    ЧУЖИЕ НАЖАТИЯ ИГНОРИРУЮТСЯ. Бота может найти кто угодно, и callback
    приходит с id того, кто нажал: всё, что не из `TELEGRAM_CHAT_ID`,
    отбрасывается. Иначе посторонний открывал бы позиции в чужом учёте.
    """
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        return 0

    offset = meta_get("tg_offset")
    payload = {"timeout": 0, "allowed_updates": ["callback_query"]}
    if offset is not None:
        payload["offset"] = int(offset)
    body = _tg_call("getUpdates", payload)
    if body is None:
        return 0

    handled = 0
    for upd in body.get("result") or []:
        meta_set("tg_offset", int(upd["update_id"]) + 1)
        cb = upd.get("callback_query")
        if not cb:
            continue
        who = str((cb.get("from") or {}).get("id", ""))
        if who != str(TELEGRAM_CHAT_ID):
            log.warning(f"Нажатие кнопки от постороннего ({who}) — игнорирую.")
            _tg_call("answerCallbackQuery",
                     {"callback_query_id": cb["id"], "text": "Не ваш бот."})
            continue
        try:
            handled += _apply_callback(cb)
        except Exception as e:  # noqa: BLE001 — кнопка не стоит торгового цикла
            log.error(f"Не удалось применить нажатие: {type(e).__name__}: {e}")
    return handled


def _apply_callback(cb: dict) -> int:
    """Применяет одно нажатие. Возвращает 1, если что-то изменилось."""
    data = str(cb.get("data") or "")
    kind, _, raw_id = data.partition(":")
    if kind not in ("b", "s") or not raw_id.isdigit():
        return 0
    row = tg_action_get(int(raw_id))
    if row is None:
        _tg_call("answerCallbackQuery",
                 {"callback_query_id": cb["id"], "text": "Лот не найден в базе."})
        return 0

    action_id = int(raw_id)
    chat_id = ((cb.get("message") or {}).get("chat") or {}).get("id", TELEGRAM_CHAT_ID)
    message_id = (cb.get("message") or {}).get("message_id") or row["message_id"]

    if kind == "b":
        # Повторное нажатие НЕ открывает вторую позицию: в учёте появился бы
        # лот, которого нет, и PnL стал бы фикцией — то же правило, что и
        # для execute_blockchain_buy().
        if row["status"] != "new":
            _tg_call("answerCallbackQuery",
                     {"callback_query_id": cb["id"],
                      "text": f"Уже отмечено: {row['status']}"})
            return 0
        pos_id = record_purchase(
            {"address": row["address"], "collection_address": row["collection"]},
            Decimal(row["buy_price_ton"]),
            Decimal(row["floor_ton"] or "0"))
        tg_action_update(action_id, status="bought", position_id=pos_id)
        note = (f"✅ Куплено — позиция #{pos_id} в учёте\n"
                f"выставлять за {Decimal(row['sale_price_ton']):.4f} TON")
        answer = f"Позиция #{pos_id} записана"
    else:
        if row["status"] != "bought":
            _tg_call("answerCallbackQuery",
                     {"callback_query_id": cb["id"],
                      "text": "Сначала отметьте «Купил»."})
            return 0
        sale = Decimal(row["sale_price_ton"])
        close_position(int(row["position_id"]), sale)
        tg_action_update(action_id, status="sold")
        # Цена продажи берётся ПЛАНОВАЯ — другой у бота нет. Если продано за
        # другую, учёт врёт, поэтому об этом сказано прямо и назван способ
        # поправить. Молча подставить плановую и промолчать значило бы
        # выдумать сделку.
        note = (f"✅ Продано по ПЛАНОВОЙ цене {sale:.4f} TON\n"
                f"Если цена была другая: run.bat --close "
                f"{row['position_id']} <цена>")
        answer = "Позиция закрыта"

    _tg_call("answerCallbackQuery", {"callback_query_id": cb["id"], "text": answer})
    if message_id:
        _tg_call("editMessageReplyMarkup", {
            "chat_id": chat_id, "message_id": message_id,
            "reply_markup": _find_buttons(action_id,
                                          bought=(kind == "b" or row["status"] == "bought"),
                                          sold=(kind == "s")),
        })
    # Через _tg_call, а не notify(): транспорт один и тот же, и подменить
    # его в тесте можно в одном месте.
    _tg_call("sendMessage", {"chat_id": chat_id, "text": note})
    log.info(f"{_Color.GREEN}Кнопка Telegram: {row['address'][:12]}… → "
             f"{'куплено' if kind == 'b' else 'продано'}{_Color.RESET}")
    return 1


def scan_finds(snap: dict, recent_sales) -> int:
    """
    Прогоняет кандидатов через фильтр БЕЗ покупки и ИИ. Возвращает число находок.

    Нужна для режима записи: там `process_item()` не вызывается вовсе, то есть
    бот копил бы рынок месяц и ни разу не сказал, что на нём вообще бывают
    подходящие лоты. А это главное, что хочется знать до первой сделки —
    годится ли выбранная коллекция под банк.

    Бесплатна по определению: `evaluate_trade()` не ходит в сеть и не трогает
    Claude. Дедупликация та же, что в торговле, иначе один и тот же лот
    приходил бы в телефон каждый цикл.
    """
    if not snap.get("floor_reliable"):
        return 0

    found = 0
    for item in snap.get("candidates", []):
        if not is_collection_trusted(item.get("collection_address", "")):
            continue
        if already_analyzed(item, snap["floor"]):
            continue
        ev = evaluate_trade(item, snap, recent_sales)
        if not ev["allowed"]:
            continue
        found += 1
        log.info(f"{_Color.GREEN}НАХОДКА{_Color.RESET} {_short(item['address'])} | "
                 f"{ev['reason']}")
        notify_find(item, snap, ev)
    return found


def notify_startup(collections):
    """
    Сообщение при старте: с какими настройками бот поднялся.

    Настройки задаются переменными окружения, а они теряются при
    перезапуске на Windows. Тихо стартовать с другими значениями, чем вы
    думаете, — самый дешёвый способ испортить запись рынка.
    """
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        return False
    mode = "СИМУЛЯЦИЯ" if DRY_RUN else "ЖИВАЯ ТОРГОВЛЯ"
    lines = [
        f"🚀 Снайпер запущен ({mode})",
        f"Коллекций: {len(collections)} | интервал {POLL_INTERVAL_SEC}с",
        f"Выборка floor: {FLOOR_SAMPLE_PAGES} стр. x {FLOOR_PAGE_SIZE}, "
        f"минимум {MIN_FLOOR_SAMPLE}",
    ]
    if BANKROLL_TON > 0:
        lines.append(f"Банк {BANKROLL_TON} TON, потолок сделки "
                     f"{max_position_size()} TON")
    if not COLLECTION_WHITELIST:
        lines.append("⚠️ whitelist пуст — защита от скам-коллекций выключена")
    notify("\n".join(lines))
    return True


