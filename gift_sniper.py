def _count_tonapi_request():
    """Счётчик запросов за сутки UTC. Обнуляется вместе с квотой — в полночь."""
    global _tonapi_used_today, _tonapi_budget_day
    today = datetime.now(timezone.utc).date()
    if _tonapi_budget_day != today:
        _tonapi_budget_day, _tonapi_used_today = today, 0
    _tonapi_used_today += 1
    if _tonapi_used_today % _BUDGET_FLUSH_EVERY == 0:
        budget_flush()


def budget_flush():
    """
    Сохраняет счётчик суток в БД.

    Зачем вообще: расход квоты живёт в памяти процесса, а квота — на стороне
    TonAPI. Бот, перезапущенный в обед, без этого считает бюджет нетронутым
    и разгоняется до POLL_INTERVAL_SEC, хотя у сервера осталась половина. То
    есть ровно тот случай, ради которого в этом файле вообще есть SQLite:
    лимит, обнуляющийся при рестарте, — не лимит.

    Сбой записи не роняет бота (наблюдение важнее учёта), но и не молчит.
    """
    global _budget_db_broken
    if _tonapi_budget_day is None:
        return
    try:
        with db_connect() as conn:
            conn.execute(
                "INSERT INTO api_budget (day, used) VALUES (?, ?) "
                "ON CONFLICT(day) DO UPDATE SET used=excluded.used",
                (_tonapi_budget_day.isoformat(), _tonapi_used_today))
        _budget_db_broken = False
    except Exception as e:                      # noqa: BLE001 — учёт не критичен
        if not _budget_db_broken:
            _budget_db_broken = True
            log.warning(f"Не удалось сохранить счётчик бюджета TonAPI ({e}). "
                        f"После перезапуска расход будет занижен.")


def budget_learn_limit(used_today: int):
    """
    Запоминает РЕАЛЬНЫЙ суточный лимит: столько запросов сервер принял, прежде
    чем отказать.

    Зачем: `TONAPI_DAILY_BUDGET` — это наша догадка. У анонимного доступа один
    лимит, у бесплатного ключа другой, у платного третий, и вслепую подобранное
    число либо занижает наблюдение (шаг реже, чем позволено), либо завышает
    (квота сгорает к обеду, и бот слепнет до полуночи).

    Отказ сервера — единственный ИЗМЕРЕННЫЙ факт о лимите, который у нас
    бывает. Он стоит одного дня слепоты, и глупо этот факт выбрасывать.
    """
    if used_today < _MIN_LEARNABLE_LIMIT:
        log.warning(
            f"{_Color.YELLOW}Отказ TonAPI при счётчике {used_today} — это НЕ "
            f"измерение лимита: наш счётчик считает только свои запросы, а "
            f"квоту могли сжечь до старта или другим процессом. Лимит не "
            f"меняю.{_Color.RESET}")
        return

    # Берём МАКСИМУМ, а не последнее значение. Лимит на стороне сервера
    # постоянен, значит лучшая его оценка — самый высокий счётчик, до
    # которого мы доходили перед отказом. Иначе один день с потерянной
    # историей занизил бы оценку навсегда.
    previous = budget_learned_limit()
    value = max(previous or 0, int(used_today))
    try:
        with db_connect() as conn:
            conn.execute(
                "INSERT INTO api_budget (day, used) VALUES ('_learned_limit', ?) "
                "ON CONFLICT(day) DO UPDATE SET used=excluded.used",
                (value,))
    except Exception as e:  # noqa: BLE001 — учёт не стоит наблюдения
        log.warning(f"Не удалось запомнить лимит TonAPI ({e}).")
        return

    if previous == value:
        return
    log.warning(f"{_Color.YELLOW}Измерен суточный лимит TonAPI: {value} "
                f"запросов (отказ пришёл на {used_today}-м). Дальше планирую "
                f"по нему, а не по TONAPI_DAILY_BUDGET={TONAPI_DAILY_BUDGET}."
                f"{_Color.RESET}")


def budget_learned_limit():
    """Выученный лимит или None. None — значит в стену ещё не упирались."""
    try:
        with db_connect() as conn:
            row = conn.execute(
                "SELECT used FROM api_budget WHERE day = '_learned_limit'"
            ).fetchone()
    except Exception:  # noqa: BLE001
        return None
    return int(row["used"]) if row else None


def effective_daily_budget() -> int:
    """
    Бюджет, по которому реально планируется интервал.

    Выученный лимит бьёт настройку, но с запасом `_LEARNED_MARGIN`: упереться
    в стену ровно на последнем запросе значит снова ослепнуть, а измерение
    приблизительное — сервер мог считать не только наши запросы.
    """
    learned = budget_learned_limit()
    if learned is None:
        return TONAPI_DAILY_BUDGET
    return max(1, int(learned * _LEARNED_MARGIN))


def budget_restore():
    """
    Поднимает расход текущих суток из БД. Вызывать один раз при старте.

    Запись за ПРОШЛЫЕ сутки не берётся: квота сбрасывается в полночь UTC,
    и вчерашний расход к сегодняшнему бюджету отношения не имеет.
    """
    global _tonapi_used_today, _tonapi_budget_day
    today = datetime.now(timezone.utc).date()
    try:
        with db_connect() as conn:
            row = conn.execute("SELECT used FROM api_budget WHERE day = ?",
                               (today.isoformat(),)).fetchone()
    except Exception as e:                      # noqa: BLE001
        log.warning(f"Не удалось прочитать счётчик бюджета TonAPI ({e}).")
        return
    if row is None:
        return
    _tonapi_budget_day, _tonapi_used_today = today, int(row["used"])
    if _tonapi_used_today:
        log.info(f"{_Color.GREY}Бюджет TonAPI: с полуночи UTC уже потрачено "
                 f"{_tonapi_used_today}/{TONAPI_DAILY_BUDGET} "
                 f"(из прошлого запуска).{_Color.RESET}")


def budget_paced_interval(collections: int) -> float:
    """
    Интервал цикла, при котором суточного бюджета хватит ДО ПОЛУНОЧИ UTC.

    Возвращает max(POLL_INTERVAL_SEC, нужный интервал): ускорять бот этот
    механизм не может, только замедлять.

    Зачем считать, а не ставить фиксированный интервал: число коллекций и
    глубина выборки меняются, и «правильный» интервал вместе с ними. Цифра,
    подобранная руками под 5 коллекций, станет неверной на седьмой.
    """
    if TONAPI_DAILY_BUDGET <= 0:
        return POLL_INTERVAL_SEC

    budget = effective_daily_budget()
    per_cycle = max(1, collections * FLOOR_SAMPLE_PAGES)
    left = budget - _tonapi_used_today
    if left <= 0:
        return POLL_INTERVAL_SEC          # бюджет исчерпан; квота сама остановит

    seconds_left = max(60.0, _next_utc_midnight() - time.time())
    cycles_affordable = left / per_cycle
    return max(POLL_INTERVAL_SEC, seconds_left / max(cycles_affordable, 1e-9))


def _next_utc_midnight() -> float:
    """Ближайшая полночь UTC как unix-время: когда сбрасывается суточная квота."""
    now = datetime.now(timezone.utc)
    tomorrow = now.replace(hour=0, minute=0, second=0, microsecond=0)
    return tomorrow.timestamp() + 86400


def _tonapi_get(url: str, params: dict, headers: dict) -> dict:
    """
    Запрос к TonAPI с соблюдением лимита по частоте и ретраями на 429.

    Зачем это здесь, а не «поднимите POLL_INTERVAL_SEC»: интервал цикла
    разносит во времени ПАЧКИ запросов, а не запросы внутри пачки. Пятнадцать
    страниц уходят за пару секунд и упираются в лимит независимо от того,
    раз в 12 секунд мы их шлём или раз в минуту.

    Ретраить важно: молча потерянная страница уменьшает выборку, а floor по
    тонкой выборке систематически ЗАВЫШАЕТСЯ (P5 вырождается в min()), то есть
    ошибается в сторону «покупай».
    """
    global _tonapi_last_call, _tonapi_quota_until
    delay = float(TONAPI_MIN_INTERVAL)

    # Суточная квота исчерпана — запрос гарантированно отклонят. Отправлять
    # его значило бы жечь и без того исчерпанный лимит и засорять лог.
    if time.time() < _tonapi_quota_until:
        left = (_tonapi_quota_until - time.time()) / 3600
        raise RateLimited(
            f"суточная квота TonAPI исчерпана, сброс через {left:.1f}ч "
            f"(полночь UTC). Лечение — бесплатный TONAPI_KEY на tonconsole.com")

    for attempt in range(TONAPI_MAX_RETRIES):
        waited = time.monotonic() - _tonapi_last_call
        if waited < delay:
            time.sleep(delay - waited)

        _tonapi_last_call = time.monotonic()
        _count_tonapi_request()
        resp = requests.get(url, params=params, headers=headers, timeout=HTTP_TIMEOUT_SEC)

        if resp.status_code == 429:
            # Суточная квота — это не «слишком часто», а «на сегодня всё».
            # Ретраить её бессмысленно: ждать надо часы, а не секунды.
            body = (resp.text or "")[:300]
            if "daily" in body.lower() or "traffic is spent" in body.lower():
                _tonapi_quota_until = _next_utc_midnight()
                # Отказ сервера — измерение лимита. Другого у нас не будет.
                budget_learn_limit(_tonapi_used_today)
                left = (_tonapi_quota_until - time.time()) / 3600
                raise RateLimited(
                    f"суточная квота анонимного доступа TonAPI исчерпана "
                    f"(сброс через {left:.1f}ч, в полночь UTC). Ретраи не "
                    f"помогут. Лечение — бесплатный TONAPI_KEY на tonconsole.com")

            if attempt == TONAPI_MAX_RETRIES - 1:
                raise RateLimited(
                    f"TonAPI отклоняет запросы (429) после {TONAPI_MAX_RETRIES} "
                    f"попыток. Без ключа квота очень мала: получите бесплатный "
                    f"TONAPI_KEY на tonconsole.com")
            # Retry-After, если сервер его прислал; иначе удваиваем паузу.
            retry_after = resp.headers.get("Retry-After")
            try:
                pause = float(retry_after) if retry_after else delay * (2 ** (attempt + 1))
            except ValueError:
                pause = delay * (2 ** (attempt + 1))
            pause = min(pause, 30.0)
            log.warning(f"TonAPI: 429, жду {pause:.1f}с и повторяю "
                        f"(попытка {attempt + 2}/{TONAPI_MAX_RETRIES}).")
            time.sleep(pause)
            continue

        resp.raise_for_status()
        return resp.json()

    # До сюда дойти нельзя: последняя попытка либо вернула данные, либо бросила.
    raise RuntimeError("TonAPI: исчерпаны попытки")


def fetch_items_tonapi(collection: str, limit: int, offset: int = 0):
    """
    ОСНОВНОЙ ИСТОЧНИК: TonAPI.io
    GET /v2/nfts/collections/{account_address}/items

    Возвращает список нормализованных лотов (см. _normalize_item).
    Работает и без ключа (низкие лимиты), с ключом TONAPI_KEY — выше квота.

    `offset` нужен для постраничной выборки при расчёте честного floor:
    у этого эндпоинта нет сортировки по цене, поэтому floor можно получить
    только достаточно широкой выборкой.
    """
    url = f"https://tonapi.io/v2/nfts/collections/{collection}/items"
    params = {"limit": limit, "offset": offset}
    headers = {"Accept": "application/json"}
    if TONAPI_KEY:
        headers["Authorization"] = f"Bearer {TONAPI_KEY}"

    data = _tonapi_get(url, params, headers)

    items = []
    for nft in data.get("nft_items", []):
        # --- Цена продажи. У TonAPI данные о продаже лежат в nft["sale"]. ---
        sale = nft.get("sale") or {}
        # Подтверждено живыми данными: sale.address — контракт продажи,
        # sale.market.name — площадка (встречаются Getgems Sales и
        # Marketapp Marketplace, у разных площадок может отличаться протокол).
        sale_address = sale.get("address", "")
        sale_market = ((sale.get("market") or {}).get("name") or "")
        price_block = sale.get("price") or {}
        sale_price_nano = price_block.get("value")          # строка нанотонов, если лот выставлен
        sale_price_ton = _nano_to_ton(sale_price_nano)

        # --- Номер минта. Ищем в метаданных / атрибутах разными способами. ---
        meta = nft.get("metadata") or {}
        mint_index = _extract_mint_index(nft, meta)

        coll = nft.get("collection") or {}
        items.append(_normalize_item(
            traits=extract_traits(meta),
            explicit_rarity_pct=_explicit_rarity_pct(meta),
            address=nft.get("address", ""),
            collection_name=coll.get("name") or meta.get("name", "Unknown"),
            # Адрес коллекции — единственное, чему можно доверять при проверке
            # на скам (имя подделывается тривиально).
            collection_address=coll.get("address", ""),
            mint_index=mint_index,
            sale_price_ton=sale_price_ton,
            is_on_sale=bool(sale_price_nano and sale_price_ton > 0),
            sale_address=sale_address,
            sale_market=sale_market,
        ))
    return items


def fetch_items_getgems(collection: str, limit: int):
    """
    ЗАПАСНОЙ ИСТОЧНИК: Getgems GraphQL.
    Вызывается, если TonAPI недоступен. Схема Getgems периодически меняется,
    поэтому запрос максимально консервативный; при неудаче — бросаем исключение.
    """
    url = "https://api.getgems.io/graphql"
    query = """
    query CollectionItems($address: String!, $first: Int!) {
      alphaNftItemSale(collectionAddress: $address, first: $first) {
        edges {
          node {
            address
            name
            index
            sale { ... on NftSaleFixPrice { fullPrice } }
          }
        }
      }
    }
    """
    payload = {"query": query, "variables": {"address": collection, "first": limit}}
    resp = requests.post(url, json=payload, timeout=HTTP_TIMEOUT_SEC)
    resp.raise_for_status()
    data = resp.json()

    edges = (((data.get("data") or {}).get("alphaNftItemSale") or {}).get("edges")) or []
    items = []
    for edge in edges:
        node = edge.get("node") or {}
        sale = node.get("sale") or {}
        price_nano = sale.get("fullPrice")
        price_ton = _nano_to_ton(price_nano)
        items.append(_normalize_item(
            address=node.get("address", ""),
            collection_name=node.get("name", "Unknown"),
            # Getgems-запрос не возвращает адрес коллекции, поэтому подставляем
            # тот, который сами запрашивали — для whitelist этого достаточно.
            collection_address=collection,
            mint_index=node.get("index"),
            sale_price_ton=price_ton,
            is_on_sale=bool(price_nano and price_ton > 0),
            # ВНИМАНИЕ: адреса контракта продажи этот запрос не возвращает,
            # поэтому лоты из запасного источника ПОКУПАТЬ НЕЛЬЗЯ —
            # execute_blockchain_buy() их отклонит. Для расчёта floor и
            # конкуренции данных хватает, для траты денег — нет.
        ))
    return items


def _extract_mint_index(nft: dict, meta: dict):
    """
    Пытается достать номер минта из разных мест метаданных TonAPI:
      - meta["mint_index"] / meta["index"]
      - атрибут с trait_type ~ 'number'/'mint'/'index'
      - число в конце названия ("Gift #777" -> 777)
    Возвращает int или None, если номер не найден.
    """
    for key in ("mint_index", "index", "number"):
        if isinstance(meta.get(key), (int, str)) and str(meta.get(key)).isdigit():
            return int(meta[key])

    for attr in meta.get("attributes", []) or []:
        trait = str(attr.get("trait_type", "")).lower()
        val = attr.get("value")
        if any(k in trait for k in ("number", "mint", "index")) and str(val).isdigit():
            return int(val)

    # Фолбэк: число после '#' в названии.
    name = str(meta.get("name", ""))
    if "#" in name:
        tail = name.split("#")[-1].strip()
        digits = "".join(ch for ch in tail if ch.isdigit())
        if digits:
            return int(digits)
    return None


def _normalize_item(address, collection_name, collection_address,
                    mint_index, sale_price_ton, is_on_sale,
                    traits=None, explicit_rarity_pct=None,
                    sale_address="", sale_market=""):
    """Единый формат лота для всего приложения (и для отправки в ИИ)."""
    return {
        "address": address,
        "collection_name": collection_name,
        "collection_address": collection_address,
        "mint_index": mint_index,
        "sale_price_ton": float(sale_price_ton),   # float для JSON-сериализации в ИИ
        "is_on_sale": is_on_sale,
        # Трейты нужны для оценки редкости — она влияет на цену Telegram Gifts
        # сильнее номера минта.
        "traits": traits or {},
        "explicit_rarity_pct": explicit_rarity_pct,
        # Получатель платежа при покупке — контракт продажи, НЕ сам NFT.
        "sale_address": sale_address,
        "sale_market": sale_market,
    }


# --- Трейты и редкость -------------------------------------------------------
# Служебные атрибуты, которые НЕ являются признаком редкости (это номер, а не
# характеристика). Номер минта оценивается отдельно, в is_pretty_mint().
# Сравнение идёт ПО СЛОВАМ, а не по подстроке: подстрочный матч выбрасывал
# легитимные трейты ("Sidekick" и "Rider" содержат "id").
_SKIP_TRAITS = {"number", "mint", "index", "serial", "id", "rarity", "no", "num"}


def extract_traits(meta: dict) -> dict:
    """
    Достаёт характеристики подарка из metadata.attributes:
    {"model": "Plush Pepe", "backdrop": "Onyx Black", "symbol": "Skull"}.

    Служебные числовые атрибуты (номер/индекс) пропускаем — они про
    нумерацию, а не про редкость.
    """
    traits = {}
    for attr in meta.get("attributes", []) or []:
        name = str(attr.get("trait_type", "")).strip().lower()
        value = attr.get("value")
        if not name or value is None:
            continue
        if set(re.split(r"[^a-z0-9]+", name)) & _SKIP_TRAITS:
            continue
        traits[name] = str(value).strip()
    return traits


def _explicit_rarity_pct(meta: dict):
    """
    Если площадка сама отдала процент редкости — доверяем ему больше, чем
    нашей оценке по выборке. Ищем атрибут с 'rarity' в названии.
    Возвращает Decimal (проценты) или None.
    """
    for attr in meta.get("attributes", []) or []:
        name = str(attr.get("trait_type", "")).strip().lower()
        if "rarity" not in name:
            continue
        raw = str(attr.get("value", "")).replace("%", "").strip()
        try:
            val = Decimal(raw)
        except (InvalidOperation, ValueError):
            continue
        if Decimal("0") < val <= Decimal("100"):
            return val
    return None


def build_trait_index(items):
    """
    Считает частоты значений трейтов по выборке:
        {"backdrop": {"Onyx Black": 3, "Sky Blue": 140}, ...}

    Возвращает (index, total_items). Это ОЦЕНКА по выборке — официального
    API редкости нет, поэтому точность растёт с размером выборки.
    """
    index, total = {}, 0
    for item in items:
        traits = item.get("traits") or {}
        if not traits:
            continue
        total += 1
        for name, value in traits.items():
            index.setdefault(name, {})
            index[name][value] = index[name].get(value, 0) + 1
    return index, total


def build_market_floors(on_sale_items):
    """
    Floor ОТДЕЛЬНО по каждой площадке: {"Getgems Sales": {"floor": D, "n": N}}.

    Зачем: TonAPI читает блокчейн, а не базу одной площадки, поэтому в выборке
    уже лежат лоты с разных маркетплейсов вперемешку. Общий floor их
    усредняет — и ровно в этом усреднении прячется разница цен между
    площадками, то есть арбитраж: купить там, где дешевле, продать там, где
    дороже.

    Это ИЗМЕРЕНИЕ, а не сигнал к покупке. Разница в цене может означать и
    разные комиссии площадок, и разный состав лотов, и просто тонкий рынок
    на одной из них. Отличить можно только по записи за несколько дней.
    """
    by_market = {}
    for it in on_sale_items:
        market = (it.get("sale_market") or "").strip() or "(площадка неизвестна)"
        by_market.setdefault(market, []).append(Decimal(str(it["sale_price_ton"])))

    out = {}
    for market, prices in by_market.items():
        prices.sort()
        out[market] = {
            "n": len(prices),
            # Тем же перцентилем, что и floor коллекции: иначе цифры
            # несопоставимы между собой.
            "floor": (_percentile(prices, FLOOR_PERCENTILE).quantize(Decimal("0.000000001"))
                      if len(prices) >= MIN_PEER_SAMPLE else None),
        }
    return out


def build_peer_prices(on_sale_items):
    """
    Цены выставленных лотов, сгруппированные по значению ключевого трейта:
        {"Cookbook": [1.2, 1.5, 4.0], "Bible": [8.0, 9.1], ...}

    Только лоты НА ПРОДАЖЕ: нас интересует, с чем конкурировать при перепродаже,
    а не какие модели вообще существуют.
    """
    peers = {}
    for it in on_sale_items:
        value = (it.get("traits") or {}).get(PEER_TRAIT)
        if not value:
            continue
        peers.setdefault(str(value), []).append(Decimal(str(it["sale_price_ton"])))
    for value in peers:
        peers[value].sort()
    return peers


def build_trait_prices(on_sale_items):
    """
    Цены выставленных лотов по КАЖДОМУ трейту, а не только по `PEER_TRAIT`:
        {"model": {"Cookbook": [1.2, 1.5]}, "backdrop": {"Onyx Black": [9.0]}}

    Зачем отдельно от `build_peer_prices()`. Та пишет только `PEER_TRAIT`
    ("model"), потому что по нему считается `eff_floor` при оценке сделки.
    Но главный тезис владельца — про ФОНЫ и УЗОРЫ: редкий фон по цене пола.
    Проверить его по записи, где фонов нет, невозможно в принципе, и каждый
    день наблюдения копил бы данные не про то.

    Поймано 22.09.2026, когда дошло до калибровки `PREMIUM_MULT`.

    ВАЖНО, что это ЦЕНЫ ПРОДАВЦОВ, а не цены сделок. Премия, посчитанная по
    ним, отвечает на вопрос «сколько ПРОСЯТ за редкий трейт», а не «сколько
    за него ПЛАТЯТ». Ставить такую премию в `PREMIUM_MULT` напрямую нельзя:
    именно у неликвида цена спроса и цена предложения расходятся сильнее
    всего. Отчёт обязан говорить это вслух.
    """
    out = {}
    for it in on_sale_items:
        price = Decimal(str(it["sale_price_ton"]))
        for name, value in (it.get("traits") or {}).items():
            out.setdefault(str(name), {}).setdefault(str(value), []).append(price)
    for name in out:
        for value in out[name]:
            out[name][value].sort()
    return out


def peer_floor(item: dict, peer_prices: dict):
    """
    Floor среди лотов с тем же ключевым трейтом: (floor | None, размер выборки).

    Считается тем же перцентилем, что и floor коллекции — по той же причине:
    один "пылевой" лот не должен определять цену целого сегмента.

    None означает "сравнить не с чем", и это НЕ синоним "всё в порядке".
    Решение о глубокой скидке без этой цифры не принимается.
    """
    value = (item.get("traits") or {}).get(PEER_TRAIT)
    if not value:
        return None, 0
    prices = (peer_prices or {}).get(str(value)) or []
    prices = [Decimal(str(p)) for p in prices]
    if len(prices) < MIN_PEER_SAMPLE:
        return None, len(prices)
    prices.sort()
    return _percentile(prices, FLOOR_PERCENTILE).quantize(Decimal("0.000000001")), len(prices)


def compute_rarity_pct(item: dict, index: dict, total: int):
    """
    Оценивает редкость лота как долю (в %) носителей его САМОГО РЕДКОГО трейта.
    Меньше процент — реже подарок.

    Приоритет: явный процент от площадки > оценка по выборке.
    Возвращает (rarity_pct | None, имя_редчайшего_трейта | None).
    None означает "оценить не удалось" — это НЕ то же самое, что "обычный".
    """
    explicit = item.get("explicit_rarity_pct")
    if explicit is not None:
        return explicit, "explicit"

    traits = item.get("traits") or {}
    if not traits or total < MIN_TRAIT_SAMPLE:
        return None, None

    rarest_pct, rarest_name = None, None
    for name, value in traits.items():
        counts = index.get(name)
        if not counts:
            continue
        seen = counts.get(value)
        if not seen:
            continue
        pct = (Decimal(seen) / Decimal(total) * Decimal("100"))
        if rarest_pct is None or pct < rarest_pct:
            rarest_pct, rarest_name = pct, name

    if rarest_pct is None:
        return None, None
    return rarest_pct.quantize(Decimal("0.01")), rarest_name


def is_rare(rarity_pct) -> bool:
    """Редкий = носителей не больше RARE_TRAIT_THRESHOLD_PCT процентов."""
    return rarity_pct is not None and rarity_pct <= RARE_TRAIT_THRESHOLD_PCT


# --- Ликвидность -------------------------------------------------------------

def compute_competition(prices, floor: Decimal) -> int:
    """
    Сколько лотов стоит в пределах COMPETITION_BAND_PCT процентов от floor.

    Зачем: floor говорит "по какой цене висит самый дешёвый", но ничего не
    говорит о том, продастся ли ваш лот. Если у floor стоит толпа, ваш
    undercut окажется в очереди и флип не закроется — прибыль на бумаге
    так и останется на бумаге.
    """
    if floor <= 0:
        return 0
    band = floor * (Decimal("1") + COMPETITION_BAND_PCT / Decimal("100"))
    return sum(1 for pr in prices if pr <= band)


def fetch_recent_sales_count(collection: str):
    """
    Считает продажи коллекции за LIQUIDITY_WINDOW_HOURS часов.

    ВНИМАНИЕ: схема этого эндпоинта TonAPI НЕ ПРОВЕРЕНА (из среды разработки
    не было сетевого доступа). Поэтому функция выключена по умолчанию
    (ENABLE_SALES_HISTORY=0) и при любой неожиданности возвращает None
    вместо выдуманного числа.

    Возвращает int (число сделок) или None, если данные недоступны.
    """
    if not ENABLE_SALES_HISTORY:
        return None

    url = f"https://tonapi.io/v2/nfts/collections/{collection}/history"
    headers = {"Accept": "application/json"}
    if TONAPI_KEY:
        headers["Authorization"] = f"Bearer {TONAPI_KEY}"

    cutoff = time.time() - LIQUIDITY_WINDOW_HOURS * 3600
    try:
        resp = requests.get(url, params={"limit": 100}, headers=headers,
                            timeout=HTTP_TIMEOUT_SEC)
        resp.raise_for_status()
        events = resp.json().get("events", [])
    except Exception as e:  # noqa: BLE001 — нет данных лучше, чем выдуманные
        log.warning(f"История продаж недоступна ({e}). Фильтр ликвидности пропущен.")
        return None

    sales = 0
    for ev in events:
        if ev.get("timestamp", 0) < cutoff:
            continue
        # Продажей считаем событие, в котором участвовал контракт продажи.
        for action in ev.get("actions", []) or []:
            if "Sale" in str(action.get("type", "")) or action.get("NftPurchase"):
                sales += 1
                break
    return sales


# --- Дедупликация ------------------------------------------------------------
# {"<address>:<price>": timestamp}. Один и тот же неизменившийся лот не должен
# уходить в Claude каждые 12 секунд — это прямые деньги за API.
_seen_cache = {}


def _floor_bucket(floor: Decimal) -> str:
    """
    Огрубляет floor до 3 значащих цифр (~1% шаг).

    Нужно для ключа дедупликации: floor всё время немного дрожит, и без
    огрубления кэш сбрасывался бы каждый цикл. Но при РЕАЛЬНОМ сдвиге floor
    вердикт обязан пересчитаться — лот, который был SKIP при floor=10,
    вполне может стать BUY при floor=15.
    """
    try:
        return f"{float(floor):.3g}"
    except (ValueError, OverflowError):
        return "0"


def already_analyzed(item: dict, floor: Decimal) -> bool:
    """
    True, если этот лот по ЭТОЙ ЖЕ цене и при ТОМ ЖЕ floor уже анализировался
    недавно.

    Ключ включает цену и floor: и то и другое — новое торговое событие,
    которое нужно пересчитать, даже если лот тот же.
    """
    key = f"{item['address']}:{item['sale_price_ton']}:{_floor_bucket(floor)}"
    now = time.monotonic()

    # Попутно чистим протухшие записи, чтобы словарь не рос бесконечно.
    for k in [k for k, ts in _seen_cache.items() if now - ts > SEEN_TTL_SEC]:
        _seen_cache.pop(k, None)

    if now - _seen_cache.get(key, -1e9) < SEEN_TTL_SEC:
        return True
    _seen_cache[key] = now
    return False


def _percentile(sorted_vals, pct: Decimal) -> Decimal:
    """
    Линейно интерполированный перцентиль по ОТСОРТИРОВАННОМУ списку Decimal.

    Зачем не min(): один случайный "пылевой" лот (например, выставленный
    по ошибке за 0.01 TON) утащил бы floor вниз и сделал бы все расчёты
    прибыли бессмысленными. Перцентиль устойчив к таким выбросам.
    """
    if not sorted_vals:
        return Decimal("0")
    if len(sorted_vals) == 1:
        return sorted_vals[0]

    k = (Decimal(len(sorted_vals) - 1) * pct) / Decimal("100")
    lo = int(k)
    hi = min(lo + 1, len(sorted_vals) - 1)
    if lo == hi:
        return sorted_vals[lo]
    frac = k - Decimal(lo)
    return sorted_vals[lo] + (sorted_vals[hi] - sorted_vals[lo]) * frac


# Кэш floor: {collection_addr: (timestamp, floor, sample_size)}.
# Внимание: это НЕ экономия запросов. Выборку приходится собирать каждый цикл,
# иначе не увидишь новые дешёвые листинги — а именно ради них бот и работает.
# Кэш нужен для другого: пережить цикл, в котором рынок отдался частично
# (часть страниц не пришла), не подменив рабочий floor случайным огрызком.
_floor_cache = {}


def _empty_snapshot(source="none"):
    """Пустой снапшот — чтобы вызывающий код не разбирал особые случаи."""
    return {"collection": "", "candidates": [], "floor": Decimal("0"),
            "sample_size": 0, "source": source, "trait_index": {}, "trait_total": 0,
            "competition": 0, "floor_reliable": False}


def get_market_snapshot(collection: str) -> dict:
    """
    Снимок рынка одним словарём:

      candidates     — самые дешёвые лоты на продажу (кандидаты на покупку)
      floor          — ЧЕСТНЫЙ floor: перцентиль по широкой выборке, не min()
      sample_size    — сколько лотов на продажу попало в выборку
      floor_reliable — достаточна ли выборка, чтобы floor чему-то соответствовал
      trait_index    — частоты трейтов по выборке (основа оценки редкости)
      trait_total    — сколько лотов с трейтами попало в индекс
      competition    — сколько продавцов стоит вплотную к floor (ликвидность)

    Почему выборка: у TonAPI /items нет сортировки по цене, он отдаёт
    элементы по индексу. Поэтому тянем FLOOR_SAMPLE_PAGES страниц и считаем
    перцентиль по собранным ценам.
    """
    cache_key = normalize_ton_address(collection) or collection
    cached = _floor_cache.get(cache_key)
    now = time.monotonic()

    all_items, source = _collect_sample(collection)
    if not all_items:
        return _empty_snapshot()

    on_sale = [it for it in all_items if it["is_on_sale"] and it["sale_price_ton"] > 0]
    prices = sorted(Decimal(str(it["sale_price_ton"])) for it in on_sale)

    if cached and (now - cached[0]) < FLOOR_CACHE_TTL_SEC and len(prices) < MIN_FLOOR_SAMPLE:
        # Выборка в этот раз вышла бедной — доверяем недавнему floor.
        floor, sample_size = cached[1], cached[2]
    else:
        floor = _percentile(prices, FLOOR_PERCENTILE).quantize(Decimal("0.000000001"))
        sample_size = len(prices)
        if sample_size >= MIN_FLOOR_SAMPLE:
            _floor_cache[cache_key] = (now, floor, sample_size)

    # Индекс редкости строим по ВСЕЙ выборке, а не только по лотам на продаже:
    # редкость — свойство коллекции, а не текущих листингов.
    trait_index, trait_total = build_trait_index(all_items)

    return {
        # Цены по сегментам: без них лот сравнивать не с чем, и бэктест
        # повторил бы ровно ту ошибку, от которой мы защищаемся.
        "peer_prices": build_peer_prices(on_sale),
        # Цены по ВСЕМ трейтам: peer_prices покрывает только PEER_TRAIT, а
        # премия за редкий ФОН по нему не считается вовсе.
        "trait_prices": build_trait_prices(on_sale),
        # Floor по площадкам: разница между ними и есть арбитраж.
        "market_floors": build_market_floors(on_sale),
        # Без этого поля снапшоты разных коллекций в записи неразличимы,
        # и бэктест подставил бы floor чужой коллекции.
        "collection": cache_key,
        "candidates": sorted(on_sale, key=lambda it: it["sale_price_ton"])[:CANDIDATES_TO_ANALYZE],
        "floor": floor,
        "sample_size": sample_size,
        "source": source,
        "trait_index": trait_index,
        "trait_total": trait_total,
        "competition": compute_competition(prices, floor),
        "floor_reliable": sample_size >= MIN_FLOOR_SAMPLE and floor > 0,
    }


def _collect_sample(collection: str):
    """
    Тянет FLOOR_SAMPLE_PAGES страниц с TonAPI; при полном провале — один
    запрос к Getgems. Возвращает (items, source).

    Частичный успех допустим: если 3 страницы из 5 пришли, работаем с ними
    и пишем предупреждение — это лучше, чем потерять весь цикл.
    """
    items, failures = [], 0
    for page in range(FLOOR_SAMPLE_PAGES):
        try:
            batch = fetch_items_tonapi(collection, FLOOR_PAGE_SIZE, offset=page * FLOOR_PAGE_SIZE)
        except RateLimited as e:
            # Упёрлись в квоту: оставшиеся страницы запрашивать бессмысленно.
            # Каждая новая попытка только углубляет блокировку, а при пяти
            # коллекциях это 70 заведомо мусорных запросов за цикл.
            log.error(f"{_Color.RED}Лимит TonAPI на странице "
                      f"{page + 1}/{FLOOR_SAMPLE_PAGES}. Остальные страницы "
                      f"пропускаю. {e}{_Color.RESET}")
            break
        except Exception as e:  # noqa: BLE001 — страница могла не прийти, это не фатально
            failures += 1
            log.warning(f"TonAPI: страница {page + 1}/{FLOOR_SAMPLE_PAGES} не получена ({e}).")
            continue
        if not batch:
            break           # коллекция закончилась — дальше тянуть нечего
        items.extend(batch)

    if items:
        if failures:
            log.warning(f"Выборка неполная: {failures} страниц потеряно. Floor менее точен.")
        return items, "TonAPI"

    # --- Полный провал TonAPI: пробуем Getgems -----------------------------
    log.warning("TonAPI недоступен полностью. Переключаюсь на Getgems...")
    try:
        return fetch_items_getgems(collection, FLOOR_PAGE_SIZE), "Getgems"
    except Exception as e:  # noqa: BLE001
        log.error(f"Оба источника недоступны. Getgems: {e}")
        return [], "none"


