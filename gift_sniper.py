# Выдумывать источник истории было бы хуже, чем не иметь бэктеста вовсе.

def record_snapshot(snap: dict, path: str = None):
    """Дописывает снимок рынка в JSONL. Одна строка — один цикл."""
    path = path or RECORD_PATH
    row = {
        "ts": time.time(),
        "collection": snap.get("collection", ""),
        "floor": str(snap["floor"]),
        "sample_size": snap["sample_size"],
        "competition": snap["competition"],
        "floor_reliable": snap["floor_reliable"],
        "trait_index": snap["trait_index"],
        "trait_total": snap["trait_total"],
        # Decimal не сериализуется в JSON — храним строками, как и floor.
        "peer_prices": {k: [str(p) for p in v]
                        for k, v in (snap.get("peer_prices") or {}).items()},
        "trait_prices": {name: {val: [str(p) for p in prices]
                                for val, prices in vals.items()}
                         for name, vals in (snap.get("trait_prices") or {}).items()},
        "market_floors": {k: {"n": v["n"],
                              "floor": (str(v["floor"]) if v["floor"] is not None else None)}
                          for k, v in (snap.get("market_floors") or {}).items()},
        "candidates": snap["candidates"],
    }
    try:
        with io_open_append(path) as f:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    except OSError as e:
        log.error(f"Не удалось записать снапшот в {path}: {e}")


def io_open_append(path):
    """Отдельная обёртка — чтобы тесты могли подменить путь записи."""
    return open(path, "a", encoding="utf-8")


def _load_recording(path: str):
    """
    Читает JSONL-запись рынка и восстанавливает Decimal.

    Битые строки пропускаются с предупреждением, а не роняют весь прогон:
    запись могла прерваться на середине строки при остановке бота.
    """
    snaps = []
    with open(path, encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
                row["floor"] = Decimal(row["floor"])
            except (json.JSONDecodeError, KeyError, InvalidOperation):
                log.warning(f"{path}:{lineno} — строка повреждена, пропускаю")
                continue
            snaps.append(row)
    snaps.sort(key=lambda r: r["ts"])
    return snaps


def _future_floor(snaps, after_ts: float, max_slack_sec: float = None):
    """
    Floor в первом снапшоте, снятом не раньше after_ts.

    Возвращает (floor, None) либо (None, причина-почему-нет).

    Две разные причины не закрыть позицию, и их важно различать:
      "end" — запись просто закончилась (ждём ещё данных);
      "gap" — снапшот есть, но слишком поздний: в записи дыра.

    Дыра опаснее конца записи, потому что она молчит. Без проверки зазора
    покупка, сделанная вечером перед выключением ПК, "закрылась" бы по floor
    следующего утра — и отчёт назвал бы это суточным удержанием. Домысливать
    за такую позицию исход означало бы подогнать результат.
    """
    if max_slack_sec is None:
        max_slack_sec = float(BACKTEST_MAX_SLACK_HOURS) * 3600
    for snap in snaps:
        if snap["ts"] >= after_ts:
            if snap["ts"] - after_ts > max_slack_sec:
                return None, "gap"
            return snap["floor"], None
    return None, "end"


def run_backtest(path: str = None, hold_hours: int = None):
    """
    Прогоняет записанную историю через боевую функцию решения.

    Модель выхода: покупаем по цене лота, через hold_hours продаём по
    floor того момента с обычным undercut'ом и теми же комиссиями.
    """
    path = path or RECORD_PATH
    hold_hours = hold_hours if hold_hours is not None else BACKTEST_HOLD_HOURS

    try:
        snaps = _load_recording(path)
    except FileNotFoundError:
        log.error(f"Записи рынка нет: {path}. Сначала соберите её: "
                  f"python gift_sniper.py --record")
        return None

    if not snaps:
        log.error(f"{path} пуст — нечего прогонять.")
        return None

    span_h = (snaps[-1]["ts"] - snaps[0]["ts"]) / 3600
    log.info(f"{_Color.BOLD}=== БЭКТЕСТ ==={_Color.RESET}")
    log.info(f"Снапшотов: {len(snaps)} | Период: {span_h:.1f}ч | "
             f"Удержание: {hold_hours}ч")
    if span_h < hold_hours * 2:
        log.warning(f"{_Color.YELLOW}Запись короче двух периодов удержания — "
                    f"результат статистически неубедителен.{_Color.RESET}")

    # Группируем по коллекциям: floor одной коллекции ничего не говорит о
    # другой, и смешивать их в одном прогоне — считать мусор.
    by_coll = {}
    for snap in snaps:
        by_coll.setdefault(snap.get("collection", ""), []).append(snap)
    if len(by_coll) > 1:
        log.info(f"В записи {len(by_coll)} коллекций — считаю каждую отдельно.")

    trades, bought_addrs = [], set()
    for coll, coll_snaps in by_coll.items():
        trades.extend(_backtest_one(coll_snaps, hold_hours, bought_addrs))

    return _report_backtest(trades, hold_hours, span_h, len(by_coll))


def _backtest_one(snaps, hold_hours: int, bought_addrs: set):
    """Прогон по снапшотам ОДНОЙ коллекции."""
    trades = []
    for snap in snaps:
        for item in snap["candidates"]:
            # Один и тот же лот не покупаем дважды за прогон.
            if item["address"] in bought_addrs:
                continue
            # recent_sales=None: в записи истории продаж нет, и подставлять
            # вместо неё число значило бы тестировать несуществующие данные.
            ev = evaluate_trade(item, snap, None)
            if not ev["allowed"]:
                continue
            if ev["buy_price"] > MAX_SPEND_PER_TRADE_TON:
                continue

            bought_addrs.add(item["address"])
            trade = {"address": item["address"], "buy": ev["buy_price"],
                     "expected": ev["net_profit"], "roi": ev["roi_pct"],
                     "entry_floor": ev["eff_floor"]}
            trade.update(_simulate_exit(snaps, snap["ts"], ev["buy_price"],
                                        hold_hours,
                                        ev["is_rare"] or ev["is_pretty"]))
            trades.append(trade)
    return trades


def _simulate_exit(snaps, buy_ts: float, buy_price: Decimal, hold_hours: int,
                   premium: bool):
    """
    Проигрывает выход из позиции по записи, вызывая ТУ ЖЕ decide_exit(),
    что и боевой бот. Отдельная копия логики выхода не проверяла бы ничего.

    Возвращает поля для записи о сделке: статус, PnL, причину и способ выхода
    ("sell" — по сроку, "stop" — по стоп-лоссу).
    """
    max_slack_sec = float(BACKTEST_MAX_SLACK_HOURS) * 3600

    for snap in snaps:
        if snap["ts"] <= buy_ts:
            continue
        held_hours = (snap["ts"] - buy_ts) / 3600
        d = decide_exit(buy_price, snap["floor"], held_hours, hold_hours)
        if d["action"] == "hold":
            continue

        # Дыра в записи обесценивает только выход ПО СРОКУ: стоп-лосс
        # сработал бы и на первом же снапшоте после перерыва, а вот "продали
        # через 24ч" при следующей отметке через 70ч — это не суточный
        # результат, как бы ни выглядела шапка отчёта.
        if (d["action"] == "sell"
                and (snap["ts"] - buy_ts) - hold_hours * 3600 > max_slack_sec):
            return {"status": "open", "missing": "gap"}

        sale = target_sale_price(snap["floor"], premium)
        proceeds = sale * (Decimal("1") - MARKETPLACE_FEE_PCT - ROYALTY_PCT)
        return {"status": "closed", "exit": d["action"],
                "exit_reason": d["reason"], "held_hours": held_hours,
                "exit_floor": snap["floor"],
                "pnl": proceeds - buy_price - GAS_FEE_TON}

    return {"status": "open", "missing": "end"}


def probe(address: str):
    """
    Диагностика: что РЕАЛЬНО отдаёт API по этому адресу и что из этого
    удалось разобрать.

    Две задачи сразу:
      1) если адрес — кошелёк, показать коллекции ваших подарков (их адреса
         можно сразу вставить в TARGET_COLLECTIONS);
      2) если адрес — коллекция, показать, что парсер извлёк из ответа,
         и ЧЕСТНО напечатать сырой JSON там, где не извлёк ничего.

    Пункт 2 существует потому, что форма ответа TonAPI в этом проекте ни разу
    не проверялась на живых данных. Сырой вывод — это то, по чему парсер
    можно починить, не гадая.
    """
    norm = normalize_ton_address(address)
    if norm is None:
        log.error(f"{address!r} не распознан как адрес TON.")
        return False

    headers = {"Accept": "application/json"}
    if TONAPI_KEY:
        headers["Authorization"] = f"Bearer {TONAPI_KEY}"

    log.info(f"{_Color.BOLD}=== ПРОВЕРКА {_short(address)} ==={_Color.RESET}")
    log.info(f"Нормализованный вид: {norm}")

    # --- Попытка 1: это кошелёк? Тогда покажем коллекции его подарков -------
    acc_url = f"https://tonapi.io/v2/accounts/{address}/nfts"
    try:
        r = requests.get(acc_url, params={"limit": 50}, headers=headers,
                         timeout=HTTP_TIMEOUT_SEC)
        if r.status_code == 200:
            items = r.json().get("nft_items", [])
            colls = {}
            for it in items:
                c = it.get("collection") or {}
                if c.get("address"):
                    colls.setdefault(c["address"], c.get("name", "?"))
            if colls:
                log.info(f"{_Color.GREEN}Это кошелёк. Коллекций среди его NFT: "
                         f"{len(colls)}{_Color.RESET}")
                for addr, name in colls.items():
                    log.info(f"  {name}")
                    log.info(f"    {addr}")
                log.info("")
                log.info("Готовая строка для запуска:")
                log.info(f"  export TARGET_COLLECTIONS=\"{','.join(colls)}\"")
                return True
    except Exception as e:  # noqa: BLE001 — это лишь одна из гипотез
        log.debug(f"Не кошелёк или ошибка: {e}")

    # --- Попытка 2: это коллекция? Проверяем парсер на живых данных --------
    url = f"https://tonapi.io/v2/nfts/collections/{address}/items"
    try:
        r = requests.get(url, params={"limit": 5}, headers=headers,
                         timeout=HTTP_TIMEOUT_SEC)
    except Exception as e:  # noqa: BLE001
        log.error(f"Сеть недоступна: {e}")
        return False

    log.info(f"HTTP {r.status_code} от {url}")
    if r.status_code != 200:
        log.error(f"Ответ: {r.text[:400]}")
        if r.status_code == 429:
            log.error("Это лимит запросов — получите TONAPI_KEY на tonconsole.com")
        return False

    raw_items = r.json().get("nft_items", [])
    if not raw_items:
        log.warning("Ответ пустой: по этому адресу предметов нет. "
                    "Скорее всего адрес не коллекции.")
        return False

    parsed = fetch_items_tonapi(address, limit=5)
    log.info(f"Предметов в ответе: {len(raw_items)} | разобрано: {len(parsed)}")

    # Проверяем КАЖДОЕ поле отдельно: молчаливо не разобранное поле — это
    # именно то, что потом ломает расчёты.
    on_sale = [i for i in parsed if i["is_on_sale"]]
    checks = [
        ("цена продажи", sum(1 for i in parsed if i["sale_price_ton"] > 0)),
        ("лоты на продаже", len(on_sale)),
        ("номер минта", sum(1 for i in parsed if i["mint_index"] is not None)),
        ("трейты", sum(1 for i in parsed if i.get("traits"))),
        ("адрес коллекции", sum(1 for i in parsed if i["collection_address"])),
    ]
    log.info("")
    for name, got in checks:
        mark = f"{_Color.GREEN}OK{_Color.RESET}" if got else f"{_Color.RED}НЕ РАЗОБРАНО{_Color.RESET}"
        log.info(f"  {name:<20} {got}/{len(parsed)}  {mark}")

    failed = [n for n, g in checks if not g]
    if failed:
        log.info("")
        log.warning(f"{_Color.YELLOW}Не разобрано: {', '.join(failed)}. "
                    f"Сырой JSON первого предмета ниже — по нему чинится парсер."
                    f"{_Color.RESET}")
        log.info(json.dumps(raw_items[0], ensure_ascii=False, indent=2)[:2500])
    else:
        log.info("")
        log.info(f"{_Color.GREEN}Парсер разобрал всё. Коллекцию можно "
                 f"добавлять в TARGET_COLLECTIONS.{_Color.RESET}")
    return not failed


def discover_collections(limit: int = 30):
    """
    Ищет коллекции, подходящие банку, вместо ручного перебора на getgems.io.

    ЧЕСТНОЕ ПРЕДУПРЕЖДЕНИЕ. Эта функция — единственная в файле, форма ответа
    для которой НЕ проверена на живых данных: сеть к tonapi.io из среды
    разработки закрыта, а эндпоинт списка коллекций в этом проекте ни разу
    не вызывался. Поэтому она написана так, чтобы при неожиданном ответе
    честно сказать "не разобрал" и напечатать сырой JSON, а не тихо вернуть
    пустой список, который выглядел бы как "подходящих коллекций нет".

    Что делает: берёт список коллекций, по каждой считает floor той же
    выборкой, что и обычный цикл, и сопоставляет с банком через
    affordability(). Дорого по запросам, поэтому режим разовый, не циклический.
    """
    log.info(f"{_Color.BOLD}=== ПОИСК КОЛЛЕКЦИЙ ПОД БАНК ==={_Color.RESET}")
    if BANKROLL_TON <= 0:
        log.error("BANKROLL_TON не задан — не с чем сопоставлять. "
                  "Укажите банк: set BANKROLL_TON=10")
        return None

    headers = {"Accept": "application/json"}
    if TONAPI_KEY:
        headers["Authorization"] = f"Bearer {TONAPI_KEY}"

    url = "https://tonapi.io/v2/nfts/collections"
    try:
        data = _tonapi_get(url, {"limit": limit, "offset": 0}, headers)
    except Exception as e:  # noqa: BLE001
        log.error(f"Список коллекций получить не удалось: {e}")
        log.info("Эндпоинт не проверен на живых данных — возможно, у него другой "
                 "адрес или он требует ключ. Пришлите вывод, поправлю.")
        return None

    raw = data.get("nft_collections") or data.get("collections") or []
    if not raw:
        log.warning(f"{_Color.YELLOW}Ответ получен, но список коллекций из него "
                    f"не разобран. Ключи ответа: {list(data)[:10]}{_Color.RESET}")
        log.info(json.dumps(data, ensure_ascii=False)[:1500])
        return None

    log.info(f"Коллекций в ответе: {len(raw)}. Считаю floor по каждой — "
             f"это {len(raw)} x {FLOOR_SAMPLE_PAGES} запросов, будет небыстро.")

    found = []
    for coll in raw:
        addr = coll.get("address") or ""
        name = ((coll.get("metadata") or {}).get("name")
                or coll.get("name") or "?")
        if not addr:
            continue
        try:
            snap = get_market_snapshot(addr)
        except Exception as e:  # noqa: BLE001 — одна коллекция не роняет поиск
            log.warning(f"{name}: {type(e).__name__}")
            continue
        if not snap.get("floor_reliable"):
            continue

        aff = affordability(snap["floor"])
        if aff["verdict"] == "нет":
            continue
        found.append({"address": addr, "name": name, "floor": snap["floor"],
                      "listings": snap["sample_size"],
                      "verdict": aff["verdict"],
                      "discount_pct": aff["discount_pct"]})

    if not found:
        log.warning(f"{_Color.YELLOW}Подходящих коллекций не нашлось. Это может "
                    f"значить и что их нет в этой выборке, и что выборка не та — "
                    f"эндпоинт отдаёт коллекции подряд, а не подарки Telegram."
                    f"{_Color.RESET}")
        return []

    found.sort(key=lambda c: c["discount_pct"])
    log.info("")
    log.info(f"{'Floor':>8} {'Лотов':>7} {'Скидка':>8} {'Банк':>6}  Коллекция")
    for c in found:
        colour = _Color.GREEN if c["verdict"] == "да" else _Color.YELLOW
        log.info(f"{c['floor']:>8.2f} {c['listings']:>7} "
                 f"{c['discount_pct']:>7.0f}% {colour}{c['verdict']:>6}"
                 f"{_Color.RESET}  {c['name']}")
        log.info(f"{'':>32}{_Color.GREY}{c['address']}{_Color.RESET}")

    log.info("")
    log.info("Готовая строка (верхние 3 по требуемой скидке):")
    log.info(f"  set TARGET_COLLECTIONS={','.join(c['address'] for c in found[:3])}")
    log.warning("Доступность банку — это ещё не торгуемость. Активна ли "
                "коллекция, покажет только запись рынка и --rank.")
    return found


def show_affordability():
    """
    Печатает, коллекции с каким floor доступны текущему банку.

    Считается без сети: это чистая арифметика риск-лимитов и комиссий.
    Нужна ДО записи рынка — наблюдать неделю за коллекцией, в которой банк
    физически не может купить, значит потратить неделю впустую.

    Два края, между которыми лежит рабочий диапазон:
      дорогие коллекции — потолок сделки (% банка) ниже прибыльной цены;
      дешёвые коллекции — газ съедает прибыль, нужна огромная скидка.
    """
    log.info(f"{_Color.BOLD}=== ЧТО ПО КАРМАНУ БАНКУ ==={_Color.RESET}")
    if BANKROLL_TON <= 0:
        log.error("BANKROLL_TON не задан — считать нечего. "
                  "Укажите банк: set BANKROLL_TON=10")
        return None

    cap = max_position_size()
    log.info(f"Банк: {BANKROLL_TON} TON | резерв: {RESERVE_TON} TON | "
             f"свободно: {available_bankroll()} TON")
    log.info(f"Потолок одной сделки: {cap} TON "
             f"(мин. из {MAX_SPEND_PER_TRADE_TON} и {MAX_POSITION_PCT}% банка)")
    log.info(f"Комиссии: площадка {MARKETPLACE_FEE_PCT * 100}% + роялти "
             f"{ROYALTY_PCT * 100}% с цены продажи, undercut "
             f"{UNDERCUT_PCT * 100}%, газ {GAS_FEE_TON} TON")
    log.info("")
    high_on = MAX_POSITION_PCT_HIGH_ROI > MAX_POSITION_PCT
    if high_on:
        log.info(f"Повышенный лимит ВКЛЮЧЁН: при ROI >= {HIGH_ROI_PCT}% "
                 f"разрешено до {MAX_POSITION_PCT_HIGH_ROI}% банка "
                 f"({max_position_size(HIGH_ROI_PCT)} TON)")
    log.info("")
    head = f"{'Floor':>8} {'Прибыльно до':>14} {'Нужна скидка':>14}  Вердикт"
    if high_on:
        head += "   | при высоком ROI"
    log.info(head)

    rows, best = [], None
    for floor in ("0.3", "0.5", "0.8", "1.0", "1.5", "2.0", "3.0", "5.0", "10.0"):
        f = Decimal(floor)
        aff = affordability(f)
        rows.append((f, aff))
        if aff["verdict"] in ("да", "узко") and (best is None or
                                                 aff["discount_pct"] < best[1]["discount_pct"]):
            best = (f, aff)
        colour = (_Color.GREEN if aff["verdict"] == "да"
                  else _Color.YELLOW if aff["verdict"] == "узко" else _Color.RED)
        line = (f"{f:>8} {aff['buy_max']:>14.2f} {aff['discount_pct']:>13.0f}%  "
                f"{colour}{aff['verdict']}{_Color.RESET}")
        if high_on:
            hi = affordability(f, HIGH_ROI_PCT)
            hi_colour = (_Color.GREEN if hi["verdict"] == "да"
                         else _Color.YELLOW if hi["verdict"] == "узко" else _Color.RED)
            line += (f"   | скидка {hi['discount_pct']:>3.0f}%  "
                     f"{hi_colour}{hi['verdict']}{_Color.RESET}")
        log.info(line)

    log.info("")
    if best is None:
        log.warning(f"{_Color.YELLOW}Банку {BANKROLL_TON} TON не подходит ни один "
                    f"из проверенных уровней floor. Либо увеличивайте банк, либо "
                    f"поднимайте MAX_POSITION_PCT — но это ваш риск, а не мой "
                    f"совет.{_Color.RESET}")
    else:
        log.info(f"{_Color.GREEN}Лучший уровень для этого банка: floor около "
                 f"{best[0]} TON — там нужна самая маленькая скидка "
                 f"({best[1]['discount_pct']:.0f}% от floor).{_Color.RESET}")
        log.info("Ищите на getgems.io коллекции Telegram Gifts с таким floor "
                 "и впишите их в TARGET_COLLECTIONS.")

    if not high_on:
        log.info("")
        log.info("Дорогой, но очень выгодный лот сейчас отсекается тем же потолком, "
                 "что и пограничный. Включить повышенный лимит:")
        log.info(f"    set HIGH_ROI_PCT=100            (с какого ROI сделка исключительная)")
        log.info(f"    set MAX_POSITION_PCT_HIGH_ROI=30  (до скольки % банка её пускать)")
        log.warning(f"{_Color.YELLOW}Прежде чем включать: высокий расчётный ROI — это "
                    f"место, где модель ошибается ЧАЩЕ всего. Глубокая скидка нередко "
                    f"означает не ошибку продавца, а причину (клон-коллекция, битый "
                    f"трейт, неликвид). Включайте после того, как бэктест покажет, что "
                    f"сделки с высоким ROI у вас закрывались в плюс.{_Color.RESET}")

    log.info("")
    log.warning("Скидка — это то, НАСКОЛЬКО ниже floor должен стоять лот, чтобы "
                "сделка была прибыльной И влезла в лимит. Чем она больше, тем "
                "реже такой лот появляется. Как часто — покажет только запись рынка.")
    return rows


def market_report(path: str = None):
    """
    Сравнивает площадки между собой по записи рынка: где систематически
    дешевле, и покрывает ли разница комиссии.

    Вопрос, на который отвечает: есть ли смысл покупать на одной площадке,
    а продавать на другой. Разовый снимок на это не отвечает — разница в
    один момент может быть случайной; значение имеет то, держится ли она.

    ЧЕГО ЭТОТ ОТЧЁТ НЕ ЗНАЕТ:
      * комиссии считаются одинаковыми для всех площадок (MARKETPLACE_FEE_PCT),
        потому что реальные ставки сняты только с Getgems;
      * разница цен может означать не арбитраж, а разный состав лотов:
        если на площадке стоят только дешёвые модели, её floor ниже законно;
      * купить на площадке можно, только если бот умеет говорить с её
        контрактом продажи. Сейчас реальная покупка не реализована вовсе,
        так что найденный арбитраж — это план, а не исполнимая сделка.
    """
    path = path or RECORD_PATH
    try:
        snaps = _load_recording(path)
    except FileNotFoundError:
        log.error(f"Записи рынка нет: {path}. Сначала соберите её: "
                  f"python gift_sniper.py --record")
        return None
    if not snaps:
        log.error(f"{path} пуст — нечего анализировать.")
        return None

    log.info(f"{_Color.BOLD}=== ПЛОЩАДКИ ==={_Color.RESET}")
    log.info(f"Запись: {path} | снапшотов {len(snaps)}")

    # Собираем floor каждой площадки по всем снапшотам каждой коллекции.
    per_coll = {}
    for snap in snaps:
        coll = snap.get("collection", "")
        mf = snap.get("market_floors") or {}
        for market, info in mf.items():
            floor = info.get("floor")
            if floor is None:
                continue
            per_coll.setdefault(coll, {}).setdefault(market, []).append(
                Decimal(str(floor)))

    if not per_coll:
        log.warning(f"{_Color.YELLOW}В записи нет данных по площадкам. Скорее "
                    f"всего запись собрана старой версией бота — она не "
                    f"сохраняла market_floors. Нужна новая запись.{_Color.RESET}")
        return None

    results = []
    for coll, markets in per_coll.items():
        log.info("")
        log.info(f"{_Color.BOLD}Коллекция {_short(coll)}{_Color.RESET}")
        log.info(f"  {'Площадка':<28} {'Floor (медиана)':>16} {'Снапшотов':>10}")

        medians = {}
        for market, floors in sorted(markets.items()):
            floors.sort()
            med = floors[len(floors) // 2]
            medians[market] = med
            log.info(f"  {market:<28} {med:>16.4f} {len(floors):>10}")

        if len(medians) < 2:
            log.info(f"  {_Color.GREY}Одна площадка — сравнивать не с чем."
                     f"{_Color.RESET}")
            continue

        cheap = min(medians, key=medians.get)
        rich = max(medians, key=medians.get)
        spread_pct = ((medians[rich] - medians[cheap]) / medians[cheap]
                      * Decimal("100"))

        # Купить на дешёвой, продать на дорогой: считаем ТОЙ ЖЕ экономикой,
        # что и обычную сделку, иначе цифры несопоставимы с остальным ботом.
        profit = compute_net_profit(medians[rich], medians[cheap])
        roi = compute_roi_pct(profit, medians[cheap])

        log.info("")
        log.info(f"  Разброс: {spread_pct:.1f}% между «{cheap}» и «{rich}»")
        if profit > 0:
            log.info(f"  {_Color.GREEN}Купить на «{cheap}» по {medians[cheap]:.4f}, "
                     f"продать на «{rich}»: +{profit:.4f} TON (ROI {roi}%)"
                     f"{_Color.RESET}")
        else:
            log.info(f"  {_Color.YELLOW}Разброс не покрывает комиссии и газ: "
                     f"{profit:.4f} TON. Арбитража нет.{_Color.RESET}")
        results.append({"collection": coll, "cheapest": cheap, "richest": rich,
                        "spread_pct": spread_pct, "profit": profit, "roi": roi})

    log.info("")
    log.warning("Разница цен между площадками — это ИЗМЕРЕНИЕ, а не сигнал. "
                "Она может означать разные комиссии, разный состав лотов или "
                "тонкий рынок на одной из них. И купить на площадке можно "
                "только когда бот умеет говорить с её контрактом продажи — "
                "сейчас реальная покупка не реализована вовсе.")
    _warn_if_recording_short(snaps)
    return results


def _load_raw_rows(path: str, source: str):
    """
    Читает запись как СЫРЫЕ строки, разбирая только ts и коллекцию.

    Именно сырые: при объединении строки переписываются дословно. Пересборка
    через json.dumps прогнала бы числа через float и незаметно испортила бы
    цены — а они в записи лежат строками именно чтобы этого не случилось.
    """
    rows = []
    with open(path, encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line.strip():
                continue
            try:
                head = json.loads(line)
                rows.append({"ts": float(head["ts"]),
                             "collection": head.get("collection", ""),
                             "line": line, "source": source})
            except (json.JSONDecodeError, KeyError, TypeError, ValueError):
                log.warning(f"{path}:{lineno} — строка повреждена, пропускаю")
    return rows


def merge_recordings(other_path: str, base_path: str = None,
                     out_path: str = None):
    """
    Объединяет две записи рынка в одну — например, с ПК и с ноутбука.

    Зачем отдельная команда, если файлы можно просто склеить. Потому что у
    склейки есть тихий сбой. Оборот в `--rank` считается как разница множеств
    самых дешёвых лотов между СОСЕДНИМИ снапшотами. Если обе машины снимали
    витрину в одно и то же время, их снапшоты в объединённой записи встанут
    вперемешку — а выборки у них чуть разные (страницы приходят не в том же
    порядке). Разница между «почти одинаковыми» выборками засчитается как
    исчезнувшие лоты, то есть как ПРОДАЖИ, которых не было.

    Метрика оборота — та самая, по которой отбирались живые коллекции, и
    испортить её значит выбрать не те коллекции, ничего не заметив.

    Поэтому: если периоды пересекаются, внутри пересечения остаётся ОДИН
    источник — тот, у кого там снапшотов больше. Это не «выбросить данные»:
    два наблюдателя одной витрины в один момент дают одно наблюдение, а не
    два.

    Ничего не перезаписывает: результат кладётся в отдельный файл, и что с
    ним делать, решает владелец.
    """
    base_path = base_path or RECORD_PATH
    out_path = out_path or (base_path + ".merged")

    if os.path.exists(out_path):
        log.error(f"{out_path} уже существует — не перезаписываю. "
                  f"Переименуйте или удалите его сами.")
        return None
    for src in (base_path, other_path):
        if not os.path.exists(src):
            log.error(f"Записи нет: {src}")
            return None

    rows = (_load_raw_rows(base_path, "A") + _load_raw_rows(other_path, "B"))
    if not rows:
        log.error("Обе записи пусты — объединять нечего.")
        return None

    log.info(f"{_Color.BOLD}=== ОБЪЕДИНЕНИЕ ЗАПИСЕЙ ==={_Color.RESET}")
    log.info(f"A: {base_path} — строк {sum(1 for r in rows if r['source'] == 'A')}")
    log.info(f"B: {other_path} — строк {sum(1 for r in rows if r['source'] == 'B')}")

    by_coll = {}
    for r in rows:
        by_coll.setdefault(r["collection"], []).append(r)

    kept, dropped = [], 0
    for coll, items in sorted(by_coll.items()):
        a = [r for r in items if r["source"] == "A"]
        b = [r for r in items if r["source"] == "B"]
        if not a or not b:
            kept.extend(items)
            continue

        lo = max(min(r["ts"] for r in a), min(r["ts"] for r in b))
        hi = min(max(r["ts"] for r in a), max(r["ts"] for r in b))
        if lo >= hi:
            kept.extend(items)          # периоды не пересекаются — всё ценно
            continue

        in_a = [r for r in a if lo <= r["ts"] <= hi]
        in_b = [r for r in b if lo <= r["ts"] <= hi]
        winner = "A" if len(in_a) >= len(in_b) else "B"
        loser_n = len(in_b) if winner == "A" else len(in_a)
        dropped += loser_n
        log.warning(f"{_Color.YELLOW}{_short(coll)}: периоды пересекаются на "
                    f"{(hi - lo) / 3600:.1f} ч. Оставляю источник {winner} "
                    f"({max(len(in_a), len(in_b))} снапшотов), отбрасываю "
                    f"{loser_n} из другого — иначе оборот посчитается с "
                    f"фантомными продажами.{_Color.RESET}")
        survivors = [r for r in items
                     if not (lo <= r["ts"] <= hi and r["source"] != winner)]

        # Одинокий снапшот проигравшего источника за краем пересечения даёт
        # не наблюдение, а ШОВ: выборки двух машин чуть разные, и переход
        # между ними засчитается как исчезнувшие лоты. Одна точка не
        # добавляет истории, ради которой стоило бы это терпеть.
        # Поймано собственным тестом: после «честного» объединения оборот
        # неподвижной витрины оказался 0.98/ч вместо нуля.
        loser = "B" if winner == "A" else "A"
        leftovers = [r for r in survivors if r["source"] == loser]
        if len(leftovers) < 2:
            dropped += len(leftovers)
            survivors = [r for r in survivors if r["source"] == winner]
        kept.extend(survivors)

    kept.sort(key=lambda r: r["ts"])
    try:
        with open(out_path, "w", encoding="utf-8") as f:
            for r in kept:
                f.write(r["line"] + "\n")
    except OSError as e:
        log.error(f"Не удалось записать {out_path}: {e}")
        return None

    span_h = (kept[-1]["ts"] - kept[0]["ts"]) / 3600 if len(kept) > 1 else 0
    log.info("")
    log.info(f"{_Color.GREEN}Готово: {out_path}{_Color.RESET}")
    log.info(f"Строк {len(kept)} (отброшено дублей {dropped}) | "
             f"коллекций {len(by_coll)} | период {span_h:.1f} ч")

    # Дыра между записями никуда не девается от объединения. Бэктест на ней
    # не закроет позиции, и надо, чтобы владелец узнал это ЗДЕСЬ, а не из
    # отчёта, в котором сделок окажется вдвое меньше ожидаемого.
    gaps = [(kept[i + 1]["ts"] - kept[i]["ts"]) / 3600
            for i in range(len(kept) - 1)]
    big = [g for g in gaps if g > float(BACKTEST_MAX_SLACK_HOURS)]
    if big:
        log.warning(f"{_Color.YELLOW}В объединённой записи {len(big)} "
                    f"разрыв(ов) больше {BACKTEST_MAX_SLACK_HOURS} ч "
                    f"(самый большой {max(big):.1f} ч). Объединение их НЕ "
                    f"лечит: позиции через разрыв бэктест не засчитает "
                    f"закрытыми.{_Color.RESET}")

    log.info(f"{_Color.GREY}Проверьте отчётом, потом замените основную "
             f"запись:{_Color.RESET}")
    log.info(f"{_Color.GREY}  python gift_sniper.py --rank {out_path}{_Color.RESET}")
    return out_path


def trait_premium_report(path: str = None):
    """
    Во сколько раз дороже floor стоят лоты с редким значением трейта.

    Это шаг калибровки `PREMIUM_MULT`, которого до сих пор не было: премия
    стояла равной 1.0 «пока не измерим», и измерить её было нечем.

    ЧТО ЭТО ЗА ЧИСЛО И ЧТО ИМ НЕЛЬЗЯ ДЕЛАТЬ. Считается по ЦЕНАМ ПРОДАВЦОВ —
    другого в записи нет, историю сделок TonAPI не отдаёт. Значит отношение
    отвечает на вопрос «сколько ПРОСЯТ за редкий трейт», а не «сколько за
    него ПЛАТЯТ». Разница между этими вопросами и есть неликвид, и у редких
    вещей она максимальна: редкий фон можно выставить за 10 floor и простоять
    с ним год.

    Поэтому число отсюда нельзя просто вписать в `PREMIUM_MULT`. Оно говорит
    другое: СУЩЕСТВУЕТ ли премия в ценах вообще и какого она порядка. Если
    её нет даже в запросах продавцов — тезис «за редкий фон переплачивают»
    неверен, и дальше копать незачем. Если есть — остаётся вопрос
    реализуемости, который решается только историей сделок.

    Берётся ПОСЛЕДНИЙ снапшот каждой коллекции: это срез витрины на один
    момент. Усреднять по времени нельзя — в разные моменты на витрине разные
    лоты, и среднее смешало бы их в несуществующий рынок.
    """
    path = path or RECORD_PATH
    try:
        snaps = _load_recording(path)
    except FileNotFoundError:
        log.error(f"Записи рынка нет: {path}. Сначала соберите её: "
                  f"python gift_sniper.py --record")
        return None
    if not snaps:
        log.error(f"{path} пуст — нечего анализировать.")
        return None

    latest = {}
    for snap in snaps:
        coll = snap.get("collection", "")
        if coll not in latest or snap["ts"] > latest[coll]["ts"]:
            latest[coll] = snap

    log.info(f"{_Color.BOLD}=== ПРЕМИЯ ЗА РЕДКИЕ ТРЕЙТЫ ==={_Color.RESET}")
    log.info(f"Запись: {path} | снапшотов {len(snaps)} | коллекций {len(latest)}")

    # Старая запись не содержит trait_prices: поле добавлено 22.09.2026.
    # Сказать об этом прямо, иначе пустой отчёт читается как «премии нет».
    with_traits = [s for s in latest.values() if s.get("trait_prices")]
    if not with_traits:
        log.warning(f"{_Color.YELLOW}В записи нет поля trait_prices — она "
                    f"собрана до 22.09.2026, когда писался только трейт "
                    f"'{PEER_TRAIT}'. Премию за ФОН по ней посчитать НЕЛЬЗЯ. "
                    f"Обновите бота и накопите запись заново — сутки уже "
                    f"дадут срез витрины.{_Color.RESET}")
        return None

    rare_ratios = []
    for coll, snap in sorted(latest.items()):
        floor = snap["floor"]
        tprices = snap.get("trait_prices") or {}
        index = snap.get("trait_index") or {}
        total = snap.get("trait_total") or 0
        if floor <= 0 or not tprices or total <= 0:
            continue

        log.info("")
        log.info(f"{_Color.BOLD}{_short(coll)}{_Color.RESET} | "
                 f"floor {floor} TON | выборка {total} предметов")

        for trait_name in sorted(tprices):
            rows = []
            for value, prices in tprices[trait_name].items():
                prices = [Decimal(str(x)) for x in prices]
                if len(prices) < MIN_PEER_SAMPLE:
                    continue
                seg = _percentile(sorted(prices), FLOOR_PERCENTILE)
                have = (index.get(trait_name) or {}).get(value)
                rarity = (Decimal(have) / Decimal(total) * 100) if have else None
                ratio = seg / floor
                rows.append((rarity, value, len(prices), seg, ratio))
                if rarity is not None and rarity <= RARE_TRAIT_THRESHOLD_PCT:
                    rare_ratios.append(ratio)

            if not rows:
                continue
            # Самые редкие сверху: именно там тезис проверяется.
            rows.sort(key=lambda r: (r[0] is None, r[0]))
            log.info(f"  трейт «{trait_name}»")
            log.info(f"    {'значение':<24}{'редкость':>9}{'лотов':>7}"
                     f"{'floor сегм.':>13}{'x floor':>9}")
            for rarity, value, n, seg, ratio in rows[:12]:
                rs = f"{rarity:.1f}%" if rarity is not None else "н/д"
                colour = (_Color.GREEN if ratio >= Decimal("1.5")
                          else _Color.GREY if ratio < Decimal("1.1") else "")
                log.info(f"    {str(value)[:24]:<24}{rs:>9}{n:>7}"
                         f"{seg:>13.2f}{colour}{ratio:>9.2f}{_Color.RESET}")

    log.info("")
    if not rare_ratios:
        log.warning(f"{_Color.YELLOW}Ни одного редкого значения с выборкой "
                    f">= {MIN_PEER_SAMPLE} лотов. Премию измерить не на чем: "
                    f"редкие трейты потому и редкие, что их мало выставляют. "
                    f"Нужна запись длиннее или коллекции крупнее.{_Color.RESET}")
        return None

    rare_ratios.sort()
    median = rare_ratios[len(rare_ratios) // 2]
    log.info(f"Редких сегментов (<= {RARE_TRAIT_THRESHOLD_PCT}% носителей) "
             f"с достаточной выборкой: {len(rare_ratios)}")
    log.info(f"{_Color.BOLD}Медианное отношение к floor: {median:.2f}x"
             f"{_Color.RESET} (разброс {rare_ratios[0]:.2f}–{rare_ratios[-1]:.2f})")

    log.info("")
    log.warning(f"{_Color.YELLOW}ЭТО ЦЕНЫ ПРОДАВЦОВ, А НЕ ЦЕНЫ СДЕЛОК. Число "
                f"выше говорит, сколько ПРОСЯТ за редкий трейт, а не сколько "
                f"платят. Вписать его в PREMIUM_MULT напрямую значит поверить, "
                f"что редкий лот уйдёт по запрошенной цене — а именно у "
                f"редких вещей запрос и спрос расходятся сильнее всего."
                f"{_Color.RESET}")
    if len(rare_ratios) < MIN_PEER_SAMPLE * 2:
        log.warning(f"{_Color.YELLOW}И выборка мала: {len(rare_ratios)} "
                    f"сегментов. Медиана по такой выборке гуляет от одного "
                    f"лота.{_Color.RESET}")
    log.info(f"{_Color.GREY}Что с этим делать: если премии нет даже в ценах "
             f"продавцов (около 1.00x) — тезис «за редкий трейт "
             f"переплачивают» не подтверждается, и PREMIUM_MULT надо оставить "
             f"равным 1.0. Если премия видна — она ВЕРХНЯЯ граница, и ставить "
             f"надо заметно ниже.{_Color.RESET}")
    return rare_ratios


def rank_collections(path: str = None):
    """
    Ранжирует коллекции из записи рынка по РЕАЛЬНОЙ активности.

    Зачем это нужно: смотреть 30 коллекций бессмысленно, если в 25 из них
    месяцами ничего не происходит. Но узнать это можно только наблюдением —
    "мёртвая" коллекция выглядит в API точно так же, как живая.

    Метрика активности — ОБОРОТ ВИТРИНЫ: сколько лотов исчезло из числа
    самых дешёвых между соседними снапшотами. Лот исчезает, когда его
    купили или сняли с продажи.

    ЧЕСТНОЕ ОГРАНИЧЕНИЕ: это измеряется по CANDIDATES_TO_ANALYZE самым
    дешёвым лотам, а не по всему объёму коллекции, и исчезновение лота —
    это продажа ИЛИ снятие, различить их без истории сделок нельзя.
    Поэтому метрика сравнительная: она говорит, где активнее, а не сколько
    именно продано.
    """
    path = path or RECORD_PATH
    try:
        snaps = _load_recording(path)
    except FileNotFoundError:
        log.error(f"Записи рынка нет: {path}. Сначала соберите её: "
                  f"python gift_sniper.py --record")
        return None
    if not snaps:
        log.error(f"{path} пуст — нечего анализировать.")
        return None

    by_coll = {}
    for snap in snaps:
        by_coll.setdefault(snap.get("collection", ""), []).append(snap)

    log.info(f"{_Color.BOLD}=== АКТИВНОСТЬ КОЛЛЕКЦИЙ ==={_Color.RESET}")
    log.info(f"Запись: {path} | снапшотов {len(snaps)} | коллекций {len(by_coll)}")

    stats = [_collection_stats(c, sn) for c, sn in by_coll.items()]
    stats.sort(key=lambda st: st["turnover_per_hour"], reverse=True)

    log.info("")
    log.info(f"{'Коллекция':<16} {'Оборот/ч':>9} {'Лотов':>7} {'Floor':>10} "
             f"{'Разброс':>9} {'Скидка':>8} {'Банк':>6}  Статус")
    for st in stats:
        colour = (_Color.RED if st["status"] != "живая"
                  else _Color.GREEN if st["turnover_per_hour"] >= 1 else "")
        # median_floor хранится как float для JSON; арифметика денег — в Decimal.
        aff = affordability(Decimal(str(st["median_floor"])))
        st["affordable"] = aff["verdict"]
        st["discount_needed_pct"] = aff["discount_pct"]
        aff_colour = (_Color.GREEN if aff["verdict"] == "да"
                      else _Color.YELLOW if aff["verdict"] == "узко"
                      else _Color.RED if aff["verdict"] == "нет" else "")
        log.info(f"{_short(st['collection']):<16} "
                 f"{st['turnover_per_hour']:>9.2f} "
                 f"{st['avg_listings']:>7.0f} "
                 f"{st['median_floor']:>10.2f} "
                 f"{st['floor_spread_pct']:>8.1f}% "
                 f"{aff['discount_pct']:>7.0f}% "
                 f"{aff_colour}{aff['verdict']:>6}{_Color.RESET}  "
                 f"{colour}{st['status']}{_Color.RESET}")

    # Активная коллекция, в которой банк не может купить, — потраченные впустую
    # дни записи и лимиты API. Сказать это надо явно, а не оставить в колонке.
    unreachable = [st for st in stats if st.get("affordable") == "нет"]
    if unreachable and BANKROLL_TON > 0:
        log.warning(f"{_Color.YELLOW}Банку {BANKROLL_TON} TON недоступны "
                    f"{len(unreachable)} из {len(stats)} коллекций: потолок сделки "
                    f"{max_position_size()} TON ниже их прибыльного диапазона. "
                    f"Наблюдать за ними можно, купить в них — нет.{_Color.RESET}")

    alive = [st for st in stats if st["status"] == "живая"]
    log.info("")
    if not alive:
        log.warning(f"{_Color.YELLOW}Ни одной живой коллекции. Либо запись слишком "
                    f"короткая, либо выбранные коллекции не торгуются.{_Color.RESET}")
    else:
        log.info(f"Живых коллекций: {len(alive)} из {len(stats)}. "
                 f"Рекомендую оставить в TARGET_COLLECTIONS верхние "
                 f"{min(3, len(alive))} — остальные только жгут лимиты API.")
    _warn_if_recording_short(snaps)
    return stats


def _collection_stats(collection: str, snaps: list) -> dict:
    """Считает метрики активности одной коллекции по её снапшотам."""
    snaps = sorted(snaps, key=lambda s: s["ts"])
    span_h = max((snaps[-1]["ts"] - snaps[0]["ts"]) / 3600, 0.0001)

    floors = [s["floor"] for s in snaps if s["floor"] > 0]
    sizes = [s["sample_size"] for s in snaps]

    # Оборот витрины: сколько дешёвых лотов исчезло между снапшотами.
    seen = [{i["address"] for i in s.get("candidates", [])} for s in snaps]
    gone = sum(len(a - b) for a, b in zip(seen, seen[1:]))

    median_floor = (sorted(floors)[len(floors) // 2] if floors else Decimal("0"))
    spread = Decimal("0")
    if floors and min(floors) > 0:
        spread = (max(floors) - min(floors)) / min(floors) * Decimal("100")

    # Диагностика "почему тихо" — это разные проблемы с разными решениями.
    if max(sizes, default=0) == 0:
        status = "офлайн (нет данных)"
    elif len(snaps) < 3:
        status = "мало снапшотов"
    elif gone == 0:
        status = "замерла (оборота нет)"
    else:
        status = "живая"

    return {
        "collection": collection or "(без адреса)",
        "snapshots": len(snaps),
        "span_hours": span_h,
        "turnover_per_hour": gone / span_h,
        "avg_listings": sum(sizes) / len(sizes) if sizes else 0,
        "median_floor": float(median_floor),
        "floor_spread_pct": float(spread),
        "status": status,
    }


def _warn_if_recording_short(snaps):
    """Короткая запись даёт красивые, но бессмысленные цифры."""
    span_h = (snaps[-1]["ts"] - snaps[0]["ts"]) / 3600
    if span_h < 24:
        log.warning(f"{_Color.YELLOW}Запись покрывает всего {span_h:.1f}ч. "
                    f"Рынок подарков неравномерен по времени суток — "
                    f"выводы по выборке меньше суток ненадёжны.{_Color.RESET}")


def _report_backtest(trades, hold_hours, span_h=None, collections=None):
    """Печатает итоги бэктеста и возвращает их словарём."""
    closed = [t for t in trades if t["status"] == "closed"]
    unresolved = len(trades) - len(closed)
    wins = [t for t in closed if t["pnl"] > 0]

    total_pnl = sum((t["pnl"] for t in closed), Decimal("0"))
    invested = sum((t["buy"] for t in closed), Decimal("0"))
    expected = sum((t["expected"] for t in closed), Decimal("0"))

    gaps = len([t for t in trades if t.get("missing") == "gap"])
    ends = unresolved - gaps
    log.info(f"Сделок отобрано: {len(trades)} | закрыто: {len(closed)} | "
             f"не закрыто: {unresolved} (запись кончилась: {ends}, "
             f"дыра в записи: {gaps})")
    stops = [t for t in closed if t.get("exit") == "stop"]
    if stops and ENABLE_STOP_LOSS:
        stop_pnl = sum((t["pnl"] for t in stops), Decimal("0"))
        log.info(f"Из них по стоп-лоссу: {len(stops)} на {stop_pnl:.4f} TON "
                 f"(порог {STOP_LOSS_PCT}% от цены покупки)")

    if gaps:
        log.warning(f"{_Color.YELLOW}{gaps} сделок выброшено из-за перерывов в "
                    f"записи: следующий снапшот нашёлся позже чем через "
                    f"{BACKTEST_MAX_SLACK_HOURS}ч после срока выхода. Пишите "
                    f"рынок непрерывно — прерывистая запись стоит данных."
                    f"{_Color.RESET}")

    if not closed:
        log.warning(f"{_Color.YELLOW}Ни одна сделка не закрылась — выводов сделать "
                    f"нельзя. Нужна запись длиннее {hold_hours}ч.{_Color.RESET}")
        return {"trades": len(trades), "closed": 0, "unresolved": unresolved,
                "gaps": gaps}

    winrate = Decimal(len(wins)) / Decimal(len(closed)) * Decimal("100")
    color = _Color.GREEN if total_pnl > 0 else _Color.RED
    log.info(f"Winrate: {winrate:.1f}% ({len(wins)}/{len(closed)})")
    log.info(f"{color}Итоговый PnL: {total_pnl:.4f} TON{_Color.RESET} "
             f"при вложениях {invested:.4f} TON")
    if invested > 0:
        log.info(f"Фактический ROI: {total_pnl / invested * 100:.2f}%")
    # Расхождение прогноза и факта — главный вывод бэктеста.
    log.info(f"Прогноз обещал {expected:.4f} TON, факт {total_pnl:.4f} TON "
             f"(расхождение {total_pnl - expected:.4f} TON)")

    best = max(closed, key=lambda t: t["pnl"])
    worst = min(closed, key=lambda t: t["pnl"])
    log.info(f"Лучшая: {best['pnl']:+.4f} TON | Худшая: {worst['pnl']:+.4f} TON")

    # --- Почему цифрам выше можно или нельзя верить -----------------------
    # Эти предупреждения стоят ПОСЛЕ чисел намеренно: их читают последними,
    # и именно они решают, что с числами делать.

    # Частота — главное практическое число отчёта. Прибыль на сделку ничего
    # не говорит о доходе, пока неизвестно, как часто сделка вообще бывает:
    # +0.55 TON раз в четыре дня и та же сумма трижды в день — это разные
    # занятия. И копить запись ради 20 сделок при такой частоте придётся
    # месяцами, что тоже надо знать заранее, а не выяснить потом.
    if span_h and span_h > 0 and trades:
        per_day = len(trades) / (span_h / 24)
        line = (f"Частота: {len(trades)} сделок за {span_h/24:.1f} суток "
                f"= {per_day:.2f} в сутки")
        if collections:
            line += f" на {collections} коллекциях"
        log.info(line)
        if per_day > 0:
            days_needed = MIN_BACKTEST_TRADES / per_day
            log.info(f"При такой частоте на {MIN_BACKTEST_TRADES} сделок "
                     f"нужно примерно {days_needed:.0f} суток записи.")

    if len(closed) < MIN_BACKTEST_TRADES:
        log.warning(
            f"{_Color.YELLOW}ВЫБОРКА МАЛА: закрытых сделок {len(closed)}, "
            f"для выводов нужно хотя бы {MIN_BACKTEST_TRADES}. При таком "
            f"числе winrate скачет на десятки процентов от ОДНОЙ сделки — "
            f"«{winrate:.0f}%» здесь означает не качество модели, а то, что "
            f"сделок почти не было. Решать по этой строке нельзя, нужна "
            f"запись длиннее.{_Color.RESET}")

    # Нулевое расхождение выглядит как «модель точна», а означать может
    # ровно обратное: floor не двигался, и предсказывать было нечего.
    flat = [t for t in closed
            if t.get("exit_floor") is not None and t.get("entry_floor") is not None
            and t["exit_floor"] == t["entry_floor"]]
    if flat and len(flat) == len(closed):
        log.warning(
            f"{_Color.YELLOW}У ВСЕХ закрытых сделок floor на выходе совпал с "
            f"floor на входе. Значит совпадение прогноза с фактом НЕ доказывает "
            f"точность модели — рынок просто стоял на месте. Проверить прогноз "
            f"можно только на сделках, где floor успел сдвинуться."
            f"{_Color.RESET}")

    return {"trades": len(trades), "closed": len(closed), "unresolved": unresolved,
            "gaps": gaps, "wins": len(wins), "winrate": winrate, "pnl": total_pnl,
            "invested": invested, "expected": expected, "flat_exits": len(flat)}


