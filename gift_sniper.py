def close_position(position_id: int, sell_price: Decimal):
    """
    Закрывает позицию и считает реальный PnL по той же экономике, что и прогноз.

    Вызывается вручную/интеграцией продажи: автоматической продажи в этой
    версии нет, поэтому метод существует, но бот его сам не дёргает.
    """
    with db_connect() as conn:
        row = conn.execute("SELECT buy_price_ton FROM positions WHERE id = ?",
                           (position_id,)).fetchone()
        if row is None:
            return None
        buy = Decimal(row["buy_price_ton"])
        proceeds = sell_price * (Decimal("1") - MARKETPLACE_FEE_PCT - ROYALTY_PCT)
        pnl = proceeds - buy - GAS_FEE_TON
        conn.execute(
            "UPDATE positions SET status='closed', sell_price_ton=?, sell_ts=?, "
            "pnl_ton=? WHERE id = ?",
            (str(sell_price), time.time(), str(pnl), position_id))
        return pnl


def decide_exit(buy_price: Decimal, current_floor: Decimal, held_hours,
                hold_hours=None) -> dict:
    """
    ДЕТЕРМИНИРОВАННОЕ решение о выходе из позиции. Ни сети, ни побочных
    эффектов — как и evaluate_trade, эта функция одна и та же для бота и
    для бэктеста.

    Возвращает {"action": "hold"|"sell"|"stop", "reason": str,
                "sell_price": Decimal | None}.

      hold — ждём покупателя по цене чуть ниже floor (основной сценарий);
      sell — вышел срок удержания, продаём по текущему floor с undercut;
      stop — floor уехал вниз настолько, что ждать больше нечего.

    Почему стоп считается от цены ПОКУПКИ, а не от floor на входе: под
    угрозой находятся вложенные деньги, а не точность прогноза.
    """
    hold_hours = hold_hours if hold_hours is not None else BACKTEST_HOLD_HOURS
    held = Decimal(str(held_hours))
    sell_price = target_sale_price(current_floor)

    if buy_price > 0:
        drop_pct = (Decimal("1") - current_floor / buy_price) * Decimal("100")
    else:
        drop_pct = Decimal("0")

    # Стоп проверяется ПЕРВЫМ: если рынок ушёл, дожидаться срока удержания
    # значит сознательно досиживать в убытке.
    if (ENABLE_STOP_LOSS and drop_pct >= STOP_LOSS_PCT
            and held >= STOP_LOSS_MIN_HOURS):
        return {"action": "stop", "sell_price": sell_price,
                "reason": (f"floor {current_floor} ниже цены покупки "
                           f"{buy_price} на {drop_pct:.1f}% "
                           f"(порог {STOP_LOSS_PCT}%)")}

    if held >= Decimal(str(hold_hours)):
        return {"action": "sell", "sell_price": sell_price,
                "reason": f"срок удержания {hold_hours}ч истёк"}

    # Ранняя просадка без выдержки — не повод фиксировать убыток: на тонком
    # рынке floor скачет от одного снятого лота.
    if ENABLE_STOP_LOSS and drop_pct >= STOP_LOSS_PCT:
        return {"action": "hold", "sell_price": None,
                "reason": (f"просадка {drop_pct:.1f}%, но позиции {held}ч "
                           f"(стоп с {STOP_LOSS_MIN_HOURS}ч)")}

    return {"action": "hold", "sell_price": None,
            "reason": f"держим: {held}ч из {hold_hours}ч, floor {current_floor}"}


def spend_since(seconds: float) -> Decimal:
    """Сколько TON потрачено за последние `seconds` секунд."""
    cutoff = time.time() - seconds
    with db_connect() as conn:
        rows = conn.execute(
            "SELECT buy_price_ton FROM positions WHERE buy_ts >= ?", (cutoff,)).fetchall()
    return sum((Decimal(r["buy_price_ton"]) for r in rows), Decimal("0"))


def open_positions_count() -> int:
    """Сколько лотов сейчас на руках (куплено, но не продано)."""
    with db_connect() as conn:
        return conn.execute(
            "SELECT COUNT(*) AS c FROM positions WHERE status='open'").fetchone()["c"]


def consecutive_losses() -> int:
    """
    Сколько убыточных сделок подряд закрыто последними.

    Это детектор "стратегия перестала работать": три убытка подряд означают,
    что предпосылки модели больше не выполняются, и продолжать — значит
    методично терять деньги.
    """
    with db_connect() as conn:
        rows = conn.execute(
            "SELECT pnl_ton FROM positions WHERE status='closed' AND pnl_ton IS NOT NULL "
            "ORDER BY sell_ts DESC LIMIT ?", (STOP_AFTER_LOSSES,)).fetchall()
    streak = 0
    for r in rows:
        if Decimal(r["pnl_ton"]) < 0:
            streak += 1
        else:
            break
    return streak


def deployed_capital() -> Decimal:
    """Сколько денег банка сейчас лежит в открытых позициях."""
    with db_connect() as conn:
        rows = conn.execute(
            "SELECT buy_price_ton FROM positions WHERE status='open'").fetchall()
    return sum((Decimal(r["buy_price_ton"]) for r in rows), Decimal("0"))


def available_bankroll() -> Decimal:
    """
    Свободные средства банка: банк минус то, что уже в позициях, минус резерв.

    Резерв не трогаем никогда: если потратить всё до копейки, не останется
    на газ, и вы не сможете даже продать купленное.
    """
    if BANKROLL_TON <= 0:
        return Decimal("0")
    return BANKROLL_TON - deployed_capital() - RESERVE_TON


def position_pct_for(roi_pct=None) -> Decimal:
    """
    Какая доля банка разрешена этой сделке.

    Обычным сделкам — MAX_POSITION_PCT. Сделкам с ROI не ниже HIGH_ROI_PCT —
    MAX_POSITION_PCT_HIGH_ROI, который по умолчанию равен обычному (механизм
    выключен). Повышенный процент НЕ отменяет остальные лимиты: банк, резерв,
    абсолютный потолок сделки и лимиты часа/суток проверяются как обычно.
    """
    if roi_pct is None:
        return MAX_POSITION_PCT
    try:
        roi = Decimal(str(roi_pct))
    except (InvalidOperation, ValueError):
        return MAX_POSITION_PCT
    if roi >= HIGH_ROI_PCT:
        return max(MAX_POSITION_PCT, MAX_POSITION_PCT_HIGH_ROI)
    return MAX_POSITION_PCT


def max_position_size(roi_pct=None) -> Decimal:
    """
    Потолок одной сделки: минимум из абсолютного лимита и доли банка.

    Доля банка важнее абсолютного числа: она масштабируется вместе с
    депозитом и не даёт одной сделке унести весь банк.

    `roi_pct` — расчётная доходность конкретной сделки. Передаётся, чтобы
    исключительно выгодная сделка не отсекалась тем же порогом, что и
    пограничная; см. MAX_POSITION_PCT_HIGH_ROI.
    """
    if BANKROLL_TON <= 0:
        return MAX_SPEND_PER_TRADE_TON
    by_pct = BANKROLL_TON * position_pct_for(roi_pct) / Decimal("100")
    return min(MAX_SPEND_PER_TRADE_TON, by_pct)


def load_wallet_key():
    """
    Читает приватный ключ из файла, проверяя права доступа.

    Возвращает (key | None, error | None). Ключ НИКОГДА не логируется,
    не пишется в БД и не уходит в уведомления.

    Права строже 0600 — обязательны: ключ, читаемый группой или всеми,
    считается скомпрометированным.
    """
    if not WALLET_KEY_FILE:
        return None, "WALLET_KEY_FILE не задан"
    if not os.path.isfile(WALLET_KEY_FILE):
        return None, f"файл ключа не найден: {WALLET_KEY_FILE}"

    # Windows не поддерживает POSIX-биты прав: os.chmod() там управляет только
    # флагом "только чтение", и st_mode всегда выглядит как 0o666 или 0o444.
    # Проверять их бессмысленно — она отвергала бы ЛЮБОЙ файл, включая
    # правильно защищённый через ACL, и живая торговля на Windows стала бы
    # невозможной с сообщением про chmod, которого там нет.
    #
    # Ворота не ослабляются, а честно признаются непроверяемыми: молчать об
    # этом нельзя, иначе пользователь решит, что бот проверил защиту ключа.
    if os.name == "nt":
        log.warning(f"{_Color.YELLOW}Windows: права на файл ключа проверить нельзя "
                    f"(POSIX-битов нет). Защитите {WALLET_KEY_FILE} сами: "
                    f"Свойства → Безопасность → оставить доступ только своей "
                    f"учётной записи.{_Color.RESET}")
    else:
        mode = os.stat(WALLET_KEY_FILE).st_mode
        if mode & 0o077:
            return None, (f"НЕБЕЗОПАСНЫЕ ПРАВА на {WALLET_KEY_FILE} "
                          f"({oct(mode & 0o777)}). Выполните: chmod 600 {WALLET_KEY_FILE}")

    try:
        with open(WALLET_KEY_FILE, encoding="utf-8") as f:
            key = f.read().strip()
    except OSError as e:
        return None, f"не удалось прочитать файл ключа: {e}"

    if not key:
        return None, "файл ключа пуст"
    return key, None


def check_risk_limits(buy_price: Decimal, roi_pct=None):
    """
    Последний контур защиты ПЕРЕД тратой денег.

    Возвращает (ok: bool, reason: str). Проверяется в порядке "от самого
    дешёвого к самому дорогому запросу".

    `roi_pct` влияет ТОЛЬКО на потолок одной сделки и только если включён
    MAX_POSITION_PCT_HIGH_ROI. Банк, резерв и лимиты часа/суток от него не
    зависят — иначе высокий расчётный ROI обнулял бы всю защиту разом.
    """
    pct = position_pct_for(roi_pct)
    cap = max_position_size(roi_pct)
    if buy_price > cap:
        return False, (f"цена {buy_price} TON выше потолка сделки {cap} TON "
                       f"({pct}% банка / абсолютный лимит)")

    # Банк — жёсткая граница: за её пределами денег просто нет.
    if BANKROLL_TON > 0:
        free = available_bankroll()
        if buy_price > free:
            return False, (f"свободно {free} TON (банк {BANKROLL_TON} − в позициях "
                           f"{deployed_capital()} − резерв {RESERVE_TON}), "
                           f"нужно {buy_price} TON")

    losses = consecutive_losses()
    if losses >= STOP_AFTER_LOSSES:
        return False, (f"{losses} убыточных сделок подряд (порог {STOP_AFTER_LOSSES}) "
                       f"— торговля остановлена")

    open_count = open_positions_count()
    if open_count >= MAX_OPEN_POSITIONS:
        return False, f"открыто {open_count} позиций (лимит {MAX_OPEN_POSITIONS})"

    hour_spend = spend_since(3600)
    if hour_spend + buy_price > MAX_SPEND_PER_HOUR_TON:
        return False, (f"часовой лимит: потрачено {hour_spend} + {buy_price} > "
                       f"{MAX_SPEND_PER_HOUR_TON} TON")

    day_spend = spend_since(86400)
    if day_spend + buy_price > MAX_SPEND_PER_DAY_TON:
        return False, (f"суточный лимит: потрачено {day_spend} + {buy_price} > "
                       f"{MAX_SPEND_PER_DAY_TON} TON")

    return True, "лимиты в норме"


def _tg_call(method: str, payload: dict):
    """
    Один запрос к Telegram. Возвращает тело ответа (dict) либо None.

    Причина выносить это отдельно — та же, по которой `notify()` проверяет
    ответ: `requests.post` бросает исключение только на СЕТЕВОЙ ошибке, а
    неверный токен это обычный HTTP 401. В лог попадает ТОЛЬКО описание от
    Telegram: токен лежит прямо в URL, и адрес логировать нельзя.
    """
    if not TELEGRAM_BOT_TOKEN:
        return None
    try:
        r = requests.post(f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/{method}",
                          json=payload, timeout=HTTP_TIMEOUT_SEC)
    except Exception as e:  # noqa: BLE001 — Telegram не стоит торгового цикла
        log.warning(f"Telegram {method}: сеть недоступна ({type(e).__name__})")
        return None
    try:
        body = r.json()
    except Exception:  # noqa: BLE001 — тело может быть не JSON
        body = {}
    if r.ok:
        return body

    # Описание от Telegram — единственное, что стоит показать. Ни URL, ни
    # заголовков: в URL лежит токен. Подсказки живут ЗДЕСЬ, а не в notify(),
    # чтобы отказ любого вызова (правка клавиатуры, ответ на нажатие) тоже
    # объяснял себя, а не отдавал голое описание.
    why = body.get("description", "") if isinstance(body, dict) else ""
    low = why.lower()
    hint = ""
    if "chat not found" in low:
        hint = (" — проверьте TELEGRAM_CHAT_ID и НАПИШИТЕ своему боту /start: "
                "бот не может начать переписку первым")
    elif "unauthorized" in low:
        hint = " — TELEGRAM_BOT_TOKEN неверный или отозван (@BotFather)"
    elif "bot was blocked" in low:
        hint = " — вы заблокировали бота, разблокируйте его в Telegram"
    log.warning(f"Telegram {method} отказал: {why}{hint}")
    return None


def _find_buttons(action_id: int, bought: bool = False, sold: bool = False):
    """
    Клавиатура «Купил / Продал» с галочками у нажатого.

    Галочка не украшение: одно и то же уведомление владелец видит и до, и
    после действия, и без отметки невозможно вспомнить, нажимал ли он уже.
    Повторное «Купил» открыло бы вторую позицию на тот же лот.

    В `callback_data` помещается 64 байта, а сырой адрес TON — 66 символов.
    Поэтому туда идёт id строки `tg_actions`, а не адрес.
    """
    return {"inline_keyboard": [[
        {"text": ("✅ Куплено" if bought else "Купил"),
         "callback_data": f"b:{action_id}"},
        {"text": ("✅ Продано" if sold else "Продал"),
         "callback_data": f"s:{action_id}"},
    ]]}


def notify(text: str) -> bool:
    """
    Шлёт уведомление в Telegram. True — Telegram подтвердил доставку.

    Необязательно: без токена тихо ничего не делает и НИКОГДА не роняет
    торговый цикл. Весь разбор ответа и подсказки («chat not found» лечится
    командой /start, «unauthorized» — новым токеном) живут в `_tg_call`,
    потому что отказать может любой вызов, а не только этот.

    ПОЧЕМУ ПРОВЕРКА ОТВЕТА ОБЯЗАТЕЛЬНА: `requests.post` бросает исключение
    только на СЕТЕВОЙ ошибке. Неверный токен — это обычный HTTP 401,
    неизвестный chat_id — 400, и код без проверки статуса считал их успехом.
    Владелец видел ровный зелёный лог и пустой чат. Поймано 21.09.2026.
    """
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        return False
    return _tg_call("sendMessage",
                    {"chat_id": TELEGRAM_CHAT_ID, "text": text}) is not None



