def execute_blockchain_buy(item_id: str, price, sale_address: str = "",
                           sale_market: str = "") -> bool:
    """
    Покупка лота. Возвращает True только если сделка ДЕЙСТВИТЕЛЬНО совершена.

    Два режима:
      DRY_RUN=1 — симуляция: зелёный лог, никаких транзакций, средства целы.
      DRY_RUN=0 — реальная подпись... которая пока НЕ РЕАЛИЗОВАНА.

    Почему здесь нет "почти рабочей" реализации: подписать транзакцию TON
    можно только через внешнюю библиотеку, API которой я не смог проверить
    в среде разработки. Код траты денег, написанный по памяти и ни разу не
    исполнявшийся, — это не автоматизация, а способ потерять банк.

    Важно: функция НИКОГДА не возвращает True, не совершив сделку. Иначе бот
    записал бы в БД позицию, которой нет, и весь учёт PnL стал бы фикцией.
    """
    # Платёж уходит на КОНТРАКТ ПРОДАЖИ, а не на сам NFT: отправка денег на
    # адрес предмета их просто потеряет. Проверка стоит ДО ветки DRY_RUN
    # намеренно — симуляция, рапортующая об успехе там, где живая покупка
    # невозможна, врёт о готовности бота. Адрес приходит из sale.address
    # TonAPI; запасной источник (Getgems GraphQL) его не отдаёт вовсе.
    if not sale_address:
        log.error(f"{_Color.RED}Адрес контракта продажи неизвестен — платить "
                  f"некуда. Сделка НЕ совершена ({_short(item_id)}).{_Color.RESET}")
        return False

    # Протокол покупки проверен только у Getgems. У другой площадки контракт
    # продажи может работать иначе — на одном наблюдённом лоте он вообще
    # совпадал с адресом предмета. Платить по непроверенному протоколу
    # значит рисковать всей суммой, а не её частью.
    if ALLOWED_MARKETS and sale_market not in ALLOWED_MARKETS:
        log.error(f"{_Color.RED}Площадка {sale_market or 'неизвестна'} не в списке "
                  f"проверенных ({', '.join(ALLOWED_MARKETS)}). Протокол её "
                  f"контракта продажи не сверялся — сделка НЕ совершена."
                  f"{_Color.RESET}")
        return False

    if DRY_RUN:
        log.info(f"{_Color.GREEN}[SUCCESS] (СИМУЛЯЦИЯ) Покупка лота "
                 f"{item_id} за {price} TON{_Color.RESET}")
        return True

    if not REAL_EXECUTOR_AVAILABLE:
        # До сюда дойти нельзя: preflight_checks() не пускает в живой режим.
        # Проверка продублирована намеренно — на случай, если кто-то вызовет
        # функцию в обход main().
        log.error(f"{_Color.RED}Исполнитель сделок недоступен ({_EXECUTOR_IMPORT_ERROR}). "
                  f"Сделка НЕ совершена. См. SETUP.md.{_Color.RESET}")
        return False

    try:
        return asyncio.run(_send_purchase(item_id, Decimal(str(price)), sale_address))
    except Exception as e:  # noqa: BLE001 — падение здесь НЕ должно выглядеть покупкой
        # Любая ошибка = сделки не было. Возврат True здесь записал бы в БД
        # позицию, которой нет, и весь учёт PnL стал бы фикцией.
        log.error(f"{_Color.RED}Покупка не удалась ({type(e).__name__}: {e}). "
                  f"Сделка НЕ совершена.{_Color.RESET}")
        return False


def build_set_price_body(new_price: Decimal, query_id: int = 0):
    """
    Тело сообщения «сменить цену» для контракта продажи Getgems v4.

    Раскладка: op 0xfd135f7b (32) + query_id (64) + new_price (coins) + 1 нулевой
    бит, без ссылок.

    Это НЕ реконструкция по документации, которой у контракта нет. Раскладка
    проверена побайтово: собранная этой функцией ячейка при цене 77 TON и
    query_id 8549106351564267300 даёт ровно тот BOC, который ушёл в живой
    операции смены цены (см. SELLING.md). Есть тест, он сверяет с дословной
    строкой — так что случайная правка раскладки не пройдёт молча.
    """
    if _Builder is None:
        raise RuntimeError(
            f"tonutils не установлен ({_EXECUTOR_IMPORT_ERROR}). "
            f"Для работы с контрактом продажи: pip install tonutils ton-core")
    nanotons = int((Decimal(str(new_price)) * NANO_PER_TON).to_integral_value())
    return (_Builder()
            .store_uint(0xfd135f7b, 32)
            .store_uint(query_id, 64)
            .store_coins(nanotons)
            .store_bit(0)
            .end_cell())


# Getgems-специфичные адреса, снятые с живого листинга (см. SELLING.md).
# Это НЕ настройки: подставить сюда своё значение значит задеплоить контракт,
# который площадка не узнает или который платит выручку не туда.
GETGEMS_DEPLOYER = "0:39d63083e48f46452ff8a04cd0d3733a90c8be299aa5951b62741759b2c17e0e"
GETGEMS_FEE_ADDR = "0:bee7a3d7b8c06f9552032c3880a56a74b702ad8b224f42bfb1ac1c33bd719080"

# 34 бита в блоке комиссий, назначение которых НЕ ОПОЗНАНО. Позиция и значение
# сняты с живого листинга и воспроизводятся дословно. Знать, что это значит, не
# требуется, чтобы повторить; требуется — чтобы менять. Не трогать.
# Проценты в хранилище контракта хранятся УМНОЖЕННЫМИ НА 100 000 в полях
# uint17 (2% -> 2000, 0% -> 0). Раскладка взята из исходника Getgems
# (packages/contracts/sources/nft-fixprice-sale-v4r1.fc, load_static_data) и
# СОШЛАСЬ с живым листингом: те 34 бита, которые раньше читались как
# "uint16=1000 + uint16=0 + 2 нулевых бита", это ровно uint17=2000 (2.0%) и
# uint17=0 (0%) — то есть комиссия площадки и роялти, независимо подтверждённые
# диалогом Getgems (0.1 на цене 5) и тремя лотами с Creator Fee 0.
_PERCENT_SCALE = 100_000
_PERCENT_BITS = 17


def _percent_to_raw(pct) -> int:
    """Доля (0.02) -> поле контракта (2000). Отрицательное и >100% отвергаются."""
    raw = int((Decimal(str(pct)) * _PERCENT_SCALE).to_integral_value())
    if not 0 <= raw < (1 << _PERCENT_BITS):
        raise ValueError(f"процент вне диапазона поля uint{_PERCENT_BITS}: {pct}")
    return raw


def build_sale_contract_data(nft_address: str, owner_address: str,
                             price: Decimal, royalty_address: str,
                             created_at: int, public_key: int,
                             marketplace_address: str = GETGEMS_DEPLOYER,
                             fee_address: str = GETGEMS_FEE_ADDR,
                             fee_percent=Decimal("0.02"),
                             royalty_percent=Decimal("0")):
    """
    Хранилище контракта продажи `nft_sale_getgems_v4`.

    Раскладка ДОКАЗАНА, а не предположена: собранная этой функцией ячейка при
    полях живого листинга даёт хеш `7b2f33f8...bca042eb` — ровно тот, что у
    задеплоенного контракта. Вместе с дословной ячейкой кода она даёт адрес
    `EQCcWUC7...kSKKFSO1`, который существует в блокчейне. Адрес — это хеш
    StateInit целиком, поэтому ошибка хоть в одном бите дала бы другой адрес;
    совпадение означает, что раскладка верна побитово. Есть тест, секция [39].

    ПОДПИСЬ — НЕ ПРЕПЯТСТВИЕ (уточнено 21.09.2026 по исходнику Getgems,
    packages/contracts/nft-fixprice-sale-v4/NftFixPriceSaleV4.data.ts). Те 512
    бит в теле деплоя — действительно ed25519-подпись, но ключ к ней НЕ
    принадлежит бэкенду Getgems: `buildNftFixPriceSaleV4R1DeployData()` зовёт
    `randomKeyPair()` и генерирует одноразовую пару НА КАЖДЫЙ ЛОТ. Открытая
    половина ложится в хранилище (те самые 256 бит), закрытой подписывается
    сообщение `0xfb5dbf47`, и контракт сверяет одно с другим
    (`check_signature(payload, signature, public_key)`).

    Смысл подписи чисто технический: сообщение задаёт цену в джеттонах, а
    словарь цен зависит от АДРЕСА контракта продажи, который сам зависит от
    хранилища — подпись разрывает эту петлю. Для продажи за TON словарь пуст,
    и сообщение деплоя не нужно вовсе.

    Практический вывод: выставить лот САМИМ можно целиком — пару ключей мы
    генерируем себе, `marketplace_address` ставим своим кошельком (в исходнике
    туда кладётся адрес деплойера), и подпись собирается локально.

    ЧЕГО ЭТА ФУНКЦИЯ НЕ РЕШАЕТ: покажет ли Getgems самостоятельно
    задеплоенный лот на витрине. Лот, о котором никто не знает, не продаётся,
    и проверить это можно только опытом.
    """
    if _Builder is None or _Address is None:
        raise RuntimeError(
            f"tonutils не установлен ({_EXECUTOR_IMPORT_ERROR}). "
            f"Для сборки контракта продажи: pip install tonutils ton-core")

    nanotons = int((Decimal(str(price)) * NANO_PER_TON).to_integral_value())

    fees = (_Builder()
            .store_address(_Address(fee_address))
            .store_address(_Address(royalty_address))
            .store_uint(_percent_to_raw(fee_percent), _PERCENT_BITS)
            .store_uint(_percent_to_raw(royalty_percent), _PERCENT_BITS)
            .store_address(_Address(nft_address))
            .store_uint(created_at, 32)
            .end_cell())

    return (_Builder()
            .store_bit(0)                                   # is_complete
            .store_address(_Address(marketplace_address))
            .store_address(_Address(owner_address))         # продавец
            .store_coins(nanotons)                          # full_price
            .store_uint(0, 32)                              # sold_at
            .store_uint(0, 64)                              # sold_query_id
            .store_uint(0, 1)                               # jetton_price_dict: пуст
            .store_uint(1, 1)                               # public_key присутствует
            .store_uint(public_key, 256)                    # ключ ЭТОГО лота
            .store_ref(fees)
            .end_cell())


def execute_set_price(sale_address: str, new_price, query_id: int = 0) -> bool:
    """
    Меняет цену уже выставленного лота. True только если транзакция ушла.

    Зачем отдельно от листинга: перевыставить лот дешевле можно ОДНОЙ короткой
    транзакцией на контракт продажи — не забирая предмет, не деплоя контракт
    заново и не собирая payload на 2148 байт. Из этого состоит стоп-лосс и
    подстройка под уехавший floor.

    Сообщение уходит на КОНТРАКТ ПРОДАЖИ. Контракт исполнит его только от
    владельца лота, поэтому чужой лот так не подвинешь; но адрес всё равно
    проверяется на разбираемость — отправка в никуда сожгла бы газ молча.
    """
    if not sale_address or normalize_ton_address(sale_address) is None:
        log.error(f"{_Color.RED}Адрес контракта продажи не распознан: "
                  f"{sale_address!r}. Цена НЕ изменена.{_Color.RESET}")
        return False

    price = Decimal(str(new_price))
    if price <= 0:
        log.error(f"{_Color.RED}Цена должна быть положительной, получено "
                  f"{new_price!r}. Цена НЕ изменена.{_Color.RESET}")
        return False

    if DRY_RUN:
        log.info(f"{_Color.GREEN}[SUCCESS] (СИМУЛЯЦИЯ) Цена лота на контракте "
                 f"{_short(sale_address)} -> {price} TON{_Color.RESET}")
        return True

    if not REAL_EXECUTOR_AVAILABLE:
        log.error(f"{_Color.RED}Исполнитель недоступен ({_EXECUTOR_IMPORT_ERROR}). "
                  f"Цена НЕ изменена. См. SETUP.md.{_Color.RESET}")
        return False

    try:
        return asyncio.run(_send_set_price(sale_address, price, query_id))
    except Exception as e:  # noqa: BLE001 — падение здесь НЕ должно выглядеть успехом
        log.error(f"{_Color.RED}Смена цены не удалась ({type(e).__name__}: {e}). "
                  f"Цена НЕ изменена.{_Color.RESET}")
        return False


async def _send_set_price(sale_address: str, price: Decimal, query_id: int) -> bool:
    """
    Отправляет сообщение смены цены на контракт продажи.

    bounce=True намеренно: если контракта по адресу нет или он отверг
    сообщение, деньги вернутся, а не осядут на несуществующем адресе.
    """
    mnemonic, err = load_wallet_key()
    if err:
        log.error(f"{_Color.RED}Кошелёк недоступен: {err}{_Color.RESET}")
        return False

    client = _TonapiClient(_trading_network(), api_key=TONAPI_KEY or None)
    wallet, _pub, _priv, _words = _WalletV4R2.from_mnemonic(client, mnemonic)
    await wallet.refresh()

    balance_ton = Decimal(wallet.balance) / NANO_PER_TON
    if balance_ton < SET_PRICE_GAS_TON:
        log.error(f"{_Color.RED}На кошельке {balance_ton:.4f} TON, на газ нужно "
                  f"{SET_PRICE_GAS_TON}. Цена НЕ изменена.{_Color.RESET}")
        return False

    log.warning(f"{_Color.YELLOW}ОТПРАВКА РЕАЛЬНОЙ ТРАНЗАКЦИИ: смена цены на "
                f"{price} TON, контракт {_short(sale_address)} "
                f"({TRADING_NETWORK}){_Color.RESET}")

    msg = await wallet.transfer(destination=sale_address,
                                amount=_to_nano(float(SET_PRICE_GAS_TON)),
                                body=build_set_price_body(price, query_id),
                                bounce=True)

    log.info(f"{_Color.GREEN}[SUCCESS] Транзакция отправлена. Новая цена "
             f"{price} TON{_Color.RESET}")
    log.info(f"Кошелёк: {wallet.address.to_str()} | сеть: {TRADING_NETWORK}")
    return msg is not None


def _trading_network():
    """
    NetworkGlobalID под TRADING_NETWORK. По умолчанию — testnet.

    Без установленной библиотеки бросает понятное исключение, а не NameError:
    «имя не определено» отправило бы искать ошибку в коде вместо того, чтобы
    поставить пакет.
    """
    if _NetworkGlobalID is None:
        raise RuntimeError(
            f"tonutils не установлен ({_EXECUTOR_IMPORT_ERROR}). "
            f"Для живой торговли: pip install tonutils ton-core")
    return (_NetworkGlobalID.MAINNET if TRADING_NETWORK == "mainnet"
            else _NetworkGlobalID.TESTNET)


async def _send_purchase(item_id: str, price: Decimal, sale_address: str) -> bool:
    """
    Отправляет платёж на КОНТРАКТ ПРОДАЖИ и подтверждает отправку.

    Возвращает True, только если транзакция реально ушла в сеть. Любой отказ —
    False: позиция, записанная без сделки, превращает учёт PnL в фикцию.

    Почему async: tonutils асинхронный, а бот синхронный. Граница проходит
    здесь, покупки редки, поэтому asyncio.run() на вызов — приемлемая цена.

    К цене добавляется PURCHASE_GAS_TON: контракту нужно оплатить исполнение
    и пересылку NFT. Излишек контракт возвращает.
    """
    mnemonic, err = load_wallet_key()
    if err:
        log.error(f"{_Color.RED}Кошелёк недоступен: {err}{_Color.RESET}")
        return False

    client = _TonapiClient(_trading_network(), api_key=TONAPI_KEY or None)
    # from_mnemonic синхронна и возвращает КОРТЕЖ, а не кошелёк (см. TONUTILS_API.md).
    wallet, _pub, _priv, _words = _WalletV4R2.from_mnemonic(client, mnemonic)

    # Состояние кошелька НЕ грузится конструктором: чтение balance без refresh()
    # бросает StateNotLoadedError. Это ровно тот случай, где код, написанный
    # по памяти, выглядит правильным и не работает.
    await wallet.refresh()

    total = price + PURCHASE_GAS_TON
    balance_ton = Decimal(wallet.balance) / NANO_PER_TON
    if balance_ton < total:
        log.error(f"{_Color.RED}На кошельке {balance_ton:.4f} TON, нужно "
                  f"{total:.4f} (цена {price} + газ {PURCHASE_GAS_TON}). "
                  f"Сделка НЕ совершена.{_Color.RESET}")
        return False

    log.warning(f"{_Color.YELLOW}ОТПРАВКА РЕАЛЬНОЙ ТРАНЗАКЦИИ: {total} TON на "
                f"контракт продажи {_short(sale_address)} за лот "
                f"{_short(item_id)} ({TRADING_NETWORK}){_Color.RESET}")

    # transfer() не собирает сообщение, а ОТПРАВЛЯЕТ его. Сумма в нанотонах.
    msg = await wallet.transfer(destination=sale_address,
                                amount=_to_nano(float(total)),
                                bounce=True)

    log.info(f"{_Color.GREEN}[SUCCESS] Транзакция отправлена. "
             f"Лот {_short(item_id)} за {price} TON{_Color.RESET}")
    log.info(f"Кошелёк: {wallet.address.to_str()} | сеть: {TRADING_NETWORK}")
    return msg is not None


