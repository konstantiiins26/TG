def target_sale_price(floor_price: Decimal, premium: bool = False) -> Decimal:
    """
    Цена, по которой мы реально сможем продать.

    Продать ПО floor нельзя: чтобы уйти первым, надо встать ниже текущего
    минимума. Поэтому целевая цена = floor минус undercut.

    `premium` (красивый номер или редкие трейты) умножает оценку на
    PREMIUM_MULT. По умолчанию он равен 1.0 — то есть красота и редкость
    НЕ повышают оценку и на решение не влияют. Это сознательно: премия —
    предположение, а не факт, и калибровать её нужно по своей записи рынка.
    """
    base = floor_price * PREMIUM_MULT if premium else floor_price
    return base * (Decimal("1") - UNDERCUT_PCT)


def max_buy_at_roi(floor_price: Decimal, min_roi_pct: Decimal,
                   premium: bool = False) -> Decimal:
    """
    Самая высокая цена покупки, при которой ROI ещё не ниже min_roi_pct.

    Выводится из определения ROI = profit/buy:
        profit = K - buy,  где K = Floor*(1-undercut)*(1-fee-royalty) - gas
        (K - buy) / buy >= t   =>   buy <= K / (1 + t),   t = min_roi_pct/100

    При min_roi_pct = 0 это в точности граница безубыточности.

    Зачем отдельно от max_profitable_buy: требование «ROI не ниже 100%» режет
    цену ВДВОЕ сильнее, чем требование «хоть какая-то прибыль». Смешивать их
    нельзя — иначе получится вывод вида «дорогая коллекция доступна при скидке
    18%», тогда как ROI в 100% требует там скидки под 60%.
    """
    sale = target_sale_price(floor_price, premium)
    k = sale * (Decimal("1") - MARKETPLACE_FEE_PCT - ROYALTY_PCT) - GAS_FEE_TON
    if k <= 0:
        return Decimal("0")
    return k / (Decimal("1") + Decimal(str(min_roi_pct)) / Decimal("100"))


def max_profitable_buy(floor_price: Decimal, premium: bool = False) -> Decimal:
    """
    Верхняя граница цены покупки, выше которой сделка убыточна.

    Частный случай max_buy_at_roi при ROI = 0:
        Buy_max = Floor * (1-undercut) * (1-fee-royalty) - gas

    Нужна, чтобы ответить на вопрос «доступна ли эта коллекция моему банку»:
    если потолок сделки (риск-лимит) ниже Buy_max, бот физически не сможет
    купить даже идеальный лот, и месяцы наблюдения за такой коллекцией
    не приведут ни к одной сделке.
    """
    return max_buy_at_roi(floor_price, Decimal("0"), premium)


def _best_sell_market(snap: dict):
    """
    Площадка с самым высоким floor в этом снапшоте: (имя, floor) или (None, None).

    Продавать выгоднее там, где дороже стоят такие же лоты. Разница между
    площадками реальна — в одной коллекции встречались «Getgems Sales» и
    «Marketapp Marketplace» с разными ценами, и общий floor эту разницу
    усредняет.

    ЧЕСТНОЕ ОГРАНИЧЕНИЕ, которое обязано быть сказано рядом с цифрой:
    комиссии у площадок РАЗНЫЕ, а проверены только ставки Getgems (2% и 0
    роялти). Более высокий floor на чужой площадке не означает больше денег
    на руки — там может быть своя комиссия и своя ликвидность.
    """
    best, best_floor = None, None
    for market, info in (snap.get("market_floors") or {}).items():
        floor = info.get("floor")
        if floor is None:
            continue
        floor = Decimal(str(floor))
        if best_floor is None or floor > best_floor:
            best, best_floor = market, floor
    return best, best_floor


def explain_trade(ev: dict, snap: dict, item: dict = None) -> list:
    """
    Расклад сделки словами: за сколько покупаю, за сколько выставлять, почему.

    Зачем отдельной функцией. Раньше бот сообщал только «профит X, ROI Y» —
    число, которое нечем проверить и по которому нельзя действовать руками.
    Владелец, получив находку, должен знать ДВЕ цены (купить и выставить) и
    видеть, из чего вторая получилась: продажа идёт НИЖЕ floor (иначе лот не
    уйдёт первым), комиссия снимается с цены ПРОДАЖИ, газ за круг
    безвозвратен. Пока эти три вещи не показаны, «профит 0.2 TON» выглядит
    как обещание, а не как расчёт.

    Вторая причина — граница. Цена покупки имеет потолок, выше которого
    сделка убыточна ПРИ ЛЮБОМ везении, и второй потолок — по минимальному
    ROI. Без них нельзя торговаться и нельзя понять, насколько близко лот к
    краю.

    Возвращает список строк (одинаково годится в лог и в Telegram).
    """
    item = item or {}
    q = lambda x: Decimal(str(x)).quantize(Decimal("0.0001"))
    basis = ("floor коллекции" if ev["eff_floor"] == snap.get("floor")
             else f"floor сегмента (похожих {ev.get('peer_n', 0)})")

    # ГДЕ покупать и ГДЕ выставлять. Лоты разных площадок приходят вперемешку
    # (TonAPI читает блокчейн, а не базу одного маркетплейса), и цена у них
    # разная. Без названия площадки владелец не найдёт лот руками, а без
    # второй площадки не увидит, что продавать выгоднее в другом месте.
    buy_market = item.get("sale_market") or "площадка неизвестна"
    sell_market, sell_floor = _best_sell_market(snap)

    lines = [
        f"ПОКУПАЮ за {q(ev['buy_price'])} TON на «{buy_market}»",
        f"ВЫСТАВЛЯЮ за {q(ev['sale_price'])} TON"
        + (f" на «{sell_market}»" if sell_market else ""),
        f"  = {q(ev['eff_floor'])} ({basis}) −{float(UNDERCUT_PCT) * 100:g}% undercut",
        f"  −{q(ev['fee_amount'])} комиссия площадки {float(MARKETPLACE_FEE_PCT) * 100:g}%",
    ]
    if ROYALTY_PCT > 0:
        lines.append(f"  −{q(ev['royalty_amount'])} роялти {float(ROYALTY_PCT) * 100:g}%")
    lines += [
        f"  = {q(ev['proceeds'])} на руки",
        f"  −{q(ev['buy_price'])} цена покупки",
        f"  −{q(GAS_FEE_TON)} газ за круг",
        f"  = {q(ev['net_profit'])} TON чистыми (ROI {ev['roi_pct']}%)",
    ]

    # ПОЧЕМУ. Undercut объясняется всегда: это единственный шаг, который
    # выглядит как «мы теряем деньги на ровном месте», а на деле он и есть
    # условие того, что лот вообще продастся.
    why = [f"почему {q(ev['sale_price'])}: продать РОВНО по floor нельзя — "
           f"чтобы уйти первым, надо встать ниже текущего минимума"]

    if ev["eff_floor"] != snap.get("floor"):
        why.append(f"оценка по сегменту {q(ev['eff_floor'])}, а не по floor "
                   f"коллекции {q(snap.get('floor', 0))}: конкурировать лот "
                   f"будет со своей моделью")

    why.append(f"дороже {q(ev['breakeven_buy'])} покупать нельзя — уйдёт в "
               f"минус; порог ROI {float(MIN_ROI_PCT):g}% требует не дороже "
               f"{q(ev['max_buy_min_roi'])}")

    # Арбитраж между площадками — но только как НАБЛЮДЕНИЕ. Разница floor
    # может означать разные комиссии, разный состав лотов или тонкий рынок на
    # одной из них; отличить можно только по записи за несколько дней.
    if sell_market and sell_market != buy_market and sell_floor is not None:
        buy_side = (snap.get("market_floors") or {}).get(buy_market) or {}
        bf = buy_side.get("floor")
        if bf is not None and Decimal(str(bf)) > 0:
            diff = (sell_floor - Decimal(str(bf))) / Decimal(str(bf)) * 100
            why.append(f"на «{sell_market}» floor {q(sell_floor)} против "
                       f"{q(bf)} на «{buy_market}» — разница {diff:.1f}%; "
                       f"комиссии площадок РАЗНЫЕ и проверены только у Getgems, "
                       f"так что это наблюдение, а не гарантия")

    if ALLOWED_MARKETS and buy_market not in ALLOWED_MARKETS:
        why.append(f"покупка ботом на «{buy_market}» ЗАПРЕЩЕНА "
                   f"(разрешено: {', '.join(ALLOWED_MARKETS)}) — протокол её "
                   f"контракта продажи не сверялся; купить можно только руками")

    if ev.get("premium_applied"):
        why.append(f"к оценке применена премия ×{PREMIUM_MULT} "
                   f"(красивый номер или редкий трейт)")
    elif ev.get("is_pretty") or ev.get("is_rare"):
        why.append("красивый номер/редкость замечены, но на цену НЕ влияют: "
                   f"PREMIUM_MULT={PREMIUM_MULT}, премия не откалибрована")

    return lines + why


def affordability(floor_price: Decimal, roi_pct=None) -> dict:
    """
    Сопоставляет коллекцию с банком: что бот реально сможет в ней купить.

    Возвращает потолок сделки, максимальную прибыльную цену и требуемую
    скидку от floor. verdict: "да" | "узко" | "нет" | "банк не задан".

    `roi_pct` — если передан, потолок считается с учётом повышенного лимита
    для исключительно выгодных сделок (MAX_POSITION_PCT_HIGH_ROI).
    """
    # Повышенный потолок действует только для сделок с высоким ROI, а такой
    # ROI сам по себе ограничивает цену сверху. Считать повышенный потолок
    # против границы безубыточности значило бы обещать доступность там, где
    # её нет.
    if roi_pct is None:
        buy_max = max_profitable_buy(floor_price)
    else:
        buy_max = max_buy_at_roi(floor_price, Decimal(str(roi_pct)))
    cap = max_position_size(roi_pct)

    if BANKROLL_TON <= 0:
        verdict = "банк не задан"
    elif buy_max <= 0:
        verdict = "нет"          # коллекция убыточна при любой цене
    elif cap >= buy_max:
        verdict = "да"           # весь прибыльный диапазон по карману
    elif cap >= buy_max / Decimal("2"):
        verdict = "узко"         # доступна только нижняя половина диапазона
    else:
        verdict = "нет"

    # Скидка от floor, которая нужна, чтобы лот одновременно был прибыльным
    # и влезал в потолок сделки.
    reachable = min(cap, buy_max) if buy_max > 0 else Decimal("0")
    if floor_price > 0 and reachable > 0:
        discount_pct = (Decimal("1") - reachable / floor_price) * Decimal("100")
    else:
        discount_pct = Decimal("100")

    return {"cap": cap, "buy_max": buy_max, "verdict": verdict,
            "discount_pct": discount_pct}


def compute_net_profit(floor_price: Decimal, buy_price: Decimal,
                       premium: bool = False) -> Decimal:
    """
    Честная формула чистой прибыли:

        Sale     = Floor * (1 - undercut)
        Proceeds = Sale - Sale*fee - Sale*royalty
        Profit   = Proceeds - Buy - gas

    Отличия от первоначального ТЗ (`(Floor-Buy) - Buy*0.05 - gas`):
      1. комиссия берётся с цены ПРОДАЖИ, а не покупки (так работают площадки);
      2. добавлено роялти создателю коллекции;
      3. продаём с undercut'ом, а не ровно по floor.
    Все три правки смещают оценку в консервативную сторону — раньше бот
    систематически завышал прибыль.
    """
    sale = target_sale_price(floor_price, premium)
    proceeds = sale * (Decimal("1") - MARKETPLACE_FEE_PCT - ROYALTY_PCT)
    return proceeds - buy_price - GAS_FEE_TON


def compute_roi_pct(net_profit: Decimal, buy_price: Decimal) -> Decimal:
    """ROI в процентах относительно вложенной суммы."""
    if buy_price <= 0:
        return Decimal("0")
    return (net_profit / buy_price * Decimal("100")).quantize(Decimal("0.01"))


def is_pretty_mint(mint_index) -> bool:
    """
    "Красивый" ли номер минта:
      - входит в топ-100 (<= 100), ИЛИ
      - в списке классических красивых номеров (777, 1111, 5555 и т.п.).
    """
    if mint_index is None:
        return False
    return mint_index <= 100 or mint_index in PRETTY_MINTS


